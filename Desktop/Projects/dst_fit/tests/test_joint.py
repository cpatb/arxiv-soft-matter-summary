"""Tests for the whole-series joint fit.

This module had no tests until 2026-08-29, which is how it shipped for two days
fitting a provably flat direction and printing ``phi_0 = 0.6912 +/- 924.4`` as an
uncertainty. The load-bearing test here is
:func:`test_phi_0_is_a_gauge_choice_not_a_parameter`, which turns the claim in the
module docstring into something that fails if it stops being true.
"""

from __future__ import annotations

import numpy as np
import pytest

from dst_fit.joint import JointFit, _stderr_or_raise, aic_from_residuals, fit_series
from dst_fit.models import WYART_CATES

TRUE_PHI_M = 0.55
TRUE_SIGMA_STAR = 5.0
TRUE_PHIS = (0.40, 0.45, 0.50)


def make_curves(phi_0=0.64, noise=0.01, seed=0):
    """A synthetic phi-series generated by the model itself."""
    model = WYART_CATES.with_fixed(eta_s=1.0, phi_0=phi_0)
    sigma = np.logspace(-1, 3, 40)
    rng = np.random.default_rng(seed)
    return [
        (
            sigma,
            model(sigma, phi, TRUE_PHI_M, TRUE_SIGMA_STAR)
            * (1.0 + noise * rng.standard_normal(sigma.size)),
        )
        for phi in TRUE_PHIS
    ]


# --------------------------------------------------------------------------
# it fits
# --------------------------------------------------------------------------
def test_recovers_the_parameters_it_was_generated_from():
    jf = fit_series(make_curves(), eta_s=1.0, phi_0=0.64, n_starts=8)
    assert jf.success
    np.testing.assert_allclose(jf.phi_m, TRUE_PHI_M, rtol=0.02)
    np.testing.assert_allclose(jf.sigma_star, TRUE_SIGMA_STAR, rtol=0.10)
    np.testing.assert_allclose(jf.phi, TRUE_PHIS, rtol=0.02)


def test_parameter_count_excludes_the_fixed_constant():
    """k = phi_m + sigma* + one phi per curve. Counting phi_0 made every AIC 2 high."""
    jf = fit_series(make_curves(), eta_s=1.0, phi_0=0.64, n_starts=6)
    assert jf.n_params == 1 + 1 + len(TRUE_PHIS) == 5

    per_curve = fit_series(
        make_curves(), eta_s=1.0, phi_0=0.64, shared_sigma_star=False, n_starts=6
    )
    assert per_curve.n_params == 1 + len(TRUE_PHIS) + len(TRUE_PHIS) == 7


def test_aic_uses_the_corrected_parameter_count():
    jf = fit_series(make_curves(), eta_s=1.0, phi_0=0.64, n_starts=6)
    np.testing.assert_allclose(
        jf.aic, aic_from_residuals(jf.residuals, jf.n_params), rtol=1e-12
    )


# --------------------------------------------------------------------------
# the gauge
# --------------------------------------------------------------------------
def test_phi_0_is_a_gauge_choice_not_a_parameter():
    """The claim the module is built on, as a test rather than a docstring.

    Wyart-Cates is exactly covariant under a common rescaling of
    ``(phi, phi_m, phi_0)``, because ``phi_J`` is homogeneous of degree one and
    the three enter only through ``phi/phi_J``. So fitting the same curves in two
    different ``phi_0`` gauges must give:

      * the *same* residuals, hence the same rmse and the same AIC, and
      * ``phi_m`` and every ``phi`` scaled by the ratio of the two ``phi_0``.

    If that ever stops holding, either the model has changed or something has
    broken the covariance, and freeing ``phi_0`` would become meaningful again.
    """
    curves = make_curves()
    a = fit_series(curves, eta_s=1.0, phi_0=0.64, n_starts=10, seed=1)
    b = fit_series(curves, eta_s=1.0, phi_0=0.56, n_starts=10, seed=1)
    ratio = 0.56 / 0.64

    np.testing.assert_allclose(b.rmse_log, a.rmse_log, rtol=1e-4)
    np.testing.assert_allclose(b.aic, a.aic, rtol=1e-6)
    np.testing.assert_allclose(b.phi_m, a.phi_m * ratio, rtol=1e-3)
    np.testing.assert_allclose(b.phi, np.asarray(a.phi) * ratio, rtol=1e-3)
    # sigma* carries no packing units, so the gauge must leave it alone.
    np.testing.assert_allclose(b.sigma_star, a.sigma_star, rtol=1e-2)


def test_phi_0_has_no_standard_error_because_it_is_not_measured():
    """NaN, not 0.0: zero would read as 'measured perfectly'."""
    jf = fit_series(make_curves(), eta_s=1.0, phi_0=0.64, n_starts=6)
    assert np.isnan(jf.stderr["phi_0"])
    assert np.isfinite(jf.stderr["phi_m"])


def test_summary_says_phi_0_is_fixed():
    jf = fit_series(make_curves(), eta_s=1.0, phi_0=0.64, n_starts=6)
    text = jf.summary()
    assert "fixed" in text and "gauge" in text
    assert "+/- nan" not in text.lower()


# --------------------------------------------------------------------------
# refusing a rank-deficient design
# --------------------------------------------------------------------------
def test_stderr_raises_on_a_rank_deficient_design():
    """The specific defect: inv() returns huge finite numbers instead of raising."""
    # Two identical columns -> exactly one flat direction.
    jac = np.zeros((50, 3))
    rng = np.random.default_rng(0)
    jac[:, 0] = rng.standard_normal(50)
    jac[:, 1] = rng.standard_normal(50)
    jac[:, 2] = jac[:, 1]

    with pytest.raises(np.linalg.LinAlgError, match="rank"):
        _stderr_or_raise(jac, 1.0, 3)


def test_stderr_works_on_a_full_rank_design():
    rng = np.random.default_rng(1)
    jac = rng.standard_normal((80, 4))
    err = _stderr_or_raise(jac, 0.25, 4)
    assert err.shape == (4,)
    assert np.all(np.isfinite(err)) and np.all(err > 0)


def test_stderr_message_names_the_singular_values():
    """The error has to be diagnosable, not just a refusal."""
    jac = np.zeros((30, 2))
    jac[:, 0] = np.linspace(-1, 1, 30)
    jac[:, 1] = jac[:, 0]
    with pytest.raises(np.linalg.LinAlgError) as exc:
        _stderr_or_raise(jac, 1.0, 2)
    assert "Singular values" in str(exc.value)


# --------------------------------------------------------------------------
# refusals
# --------------------------------------------------------------------------
@pytest.mark.parametrize("bad", [0.0, 1.0, -0.5, np.nan, np.inf])
def test_rejects_a_phi_0_that_is_not_a_packing_fraction(bad):
    with pytest.raises(ValueError, match="phi_0"):
        fit_series(make_curves(), eta_s=1.0, phi_0=bad, n_starts=2)


def test_rejects_a_phi_0_that_leaves_no_room_for_phi_m():
    with pytest.raises(ValueError, match="no room"):
        fit_series(make_curves(), eta_s=1.0, phi_0=0.25, n_starts=2)


def test_needs_at_least_two_curves():
    with pytest.raises(ValueError, match="at least two"):
        fit_series(make_curves()[:1], eta_s=1.0, phi_0=0.64)


def test_jointfit_is_constructible_for_downstream_use():
    """A guard on the dataclass field list, which gates unpack by name."""
    jf = fit_series(make_curves(), eta_s=1.0, phi_0=0.64, n_starts=6)
    assert isinstance(jf, JointFit)
    for key in ("phi_0", "phi_m", "sigma_star", "phi"):
        assert key in jf.stderr
