"""Gate N2 / G1: does the fitter recover known parameters, and is its uncertainty honest?

Recovering a parameter once proves very little. `diff_calibrate.py` in the
tier-0 repo recovers three parameters to three digits from data generated by the
model it fits, and that says only that autodiff works. The question that matters
is whether the quoted uncertainty means anything, so G1 is a **coverage** test:
over many noise realisations, how often does the 2-sigma interval actually
contain the truth?

Pass conditions, fixed before the run:

  G1a  point recovery: median |recovered - true| / true < 5% for every parameter
  G1b  coverage: the 2-sigma interval contains the true value in >= 80% of trials
       for every parameter. Nominal is 95.4%; the bar is set lower because the
       linearised covariance is a local Gaussian approximation and these models
       are nonlinear in their parameters, so some under-coverage is expected and
       honest. Coverage far below 80% would mean the reported errors are
       fiction.
  G1c  RETIRED, and it FAILED on 2026-08-27 before being retired. It asked that
       removing the top 20% of the stress range inflate the *sigma-star* standard
       error by >= 3x; the measured inflation was 1.14x. The gate named the
       wrong parameter. sigma* is set by where the frictional transition sits,
       which the retained data still brackets; the high-stress plateau
       constrains *phi_m*, and that is what a top-end cut destroys. Measured
       inflation under progressive truncation, at cuts to 80/60/50% of the
       stress range:

           phi          0.99x   1.10x   1.13x
           phi_m        1.31x   8.52x  154.70x
           sigma_star   1.14x   2.85x   14.11x

       The fitter was behaving correctly the whole time and the gate was wrong.
       Recorded rather than deleted, because a threshold quietly edited until it
       passes is worth nothing.

  G1c' censoring, restated structurally: under progressive truncation of the
       stress range, stderr(phi_m) must inflate strictly more than stderr(phi)
       at every cut level. This follows from what each parameter reads off the
       curve rather than from any observed number, so unlike a magnitude
       threshold it cannot be tuned to make the run pass. It also tests the
       thing actually worth testing, which is whether the fitter notices *which*
       parameter lost its evidence.

Run:  python scripts/gate_n2.py
Exit code is 0 only if every gate passes.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from dst_fit.fitting import fit_model, synthetic_curve  # noqa: E402
from dst_fit.models import get_model  # noqa: E402

N_TRIALS = 100
NOISE = 0.02  # 2% relative scatter in viscosity

MEDIAN_REL_ERR_MAX = 0.05  # G1a
COVERAGE_MIN = 0.80  # G1b
CENSOR_CUTS = (0.8, 0.6, 0.5)  # G1c': fractions of the stress range retained

# Truth used for each model, chosen inside the bounds and in a physically
# sensible place rather than at a convenient optimum.
TRUTH = {
    "wyart_cates": (0.52, 0.58, 5.0),
    "herschel_bulkley": (2.0, 1.5, 0.6),
    "ellis": (10.0, 0.05, 3.0, 1.4),
}

# Stress windows roughly matching the corn-starch sweeps (1e-2 to 1e3 Pa).
SIGMA = np.logspace(-2, 3, 40)


def coverage_study(name: str, truth: tuple[float, ...]) -> dict:
    model = get_model(name)
    truth_arr = np.asarray(truth, dtype=float)
    hits = np.zeros(model.n_params)
    rel_errs: list[np.ndarray] = []
    n_ok = 0

    for seed in range(N_TRIALS):
        sigma, eta = synthetic_curve(model, truth, SIGMA, noise=NOISE, seed=seed)
        try:
            r = fit_model(model, sigma, eta, n_starts=4, seed=seed)
        except (RuntimeError, ValueError):
            continue
        if not np.all(np.isfinite(r.stderr)):
            continue
        n_ok += 1
        rel_errs.append(np.abs(r.params - truth_arr) / np.abs(truth_arr))
        hits += (np.abs(r.params - truth_arr) <= 2.0 * r.stderr).astype(float)

    if n_ok == 0:
        return {"model": name, "n_ok": 0, "ok": False}

    return {
        "model": name,
        "n_ok": n_ok,
        "median_rel_err": np.median(np.vstack(rel_errs), axis=0),
        "coverage": hits / n_ok,
        "param_names": model.param_names,
    }


def censoring_study() -> dict:
    """Truncate the stress range progressively and watch which parameter suffers.

    phi_m is read off the high-stress plateau, phi off the whole curve. Removing
    the top of the range should therefore cost phi_m more than phi at every cut.
    That ordering is the gate; the magnitudes are reported but not thresholded,
    because a magnitude bar set after seeing the numbers is not a test.
    """
    model = get_model("wyart_cates")
    truth = TRUTH["wyart_cates"]
    sigma, eta = synthetic_curve(model, truth, SIGMA, noise=NOISE, seed=0)
    full = fit_model(model, sigma, eta, n_starts=4, seed=0)

    i_phi = model.param_names.index("phi")
    i_phim = model.param_names.index("phi_m")

    rows = []
    for frac in CENSOR_CUTS:
        keep = slice(0, int(frac * sigma.size))
        cut = fit_model(model, sigma[keep], eta[keep], n_starts=4, seed=0)
        infl = cut.stderr / full.stderr
        rows.append(
            {
                "frac": frac,
                "sigma_max": float(sigma[keep].max()),
                "n": cut.n_points,
                "inflation": infl,
                "ordered": bool(np.isfinite(infl[i_phim]) and infl[i_phim] > infl[i_phi]),
            }
        )
    return {"full": full, "rows": rows, "i_phi": i_phi, "i_phim": i_phim, "model": model}


def main() -> int:
    failures: list[str] = []
    print(f"G1: {N_TRIALS} trials per model, {NOISE:.0%} lognormal noise in viscosity\n")

    for name, truth in TRUTH.items():
        res = coverage_study(name, truth)
        if not res.get("n_ok"):
            failures.append(f"G1: {name}: every trial failed to fit")
            continue

        print(f"  {name}  ({res['n_ok']}/{N_TRIALS} converged with finite errors)")
        for j, pname in enumerate(res["param_names"]):
            mre = res["median_rel_err"][j]
            cov = res["coverage"][j]
            flags = []
            if mre > MEDIAN_REL_ERR_MAX:
                flags.append("G1a")
                failures.append(f"G1a: {name}.{pname}: median rel err {mre:.3f}")
            if cov < COVERAGE_MIN:
                flags.append("G1b")
                failures.append(f"G1b: {name}.{pname}: 2-sigma coverage {cov:.2f}")
            mark = ("  <-- " + ",".join(flags)) if flags else ""
            print(
                f"      {pname:>12s}  true={truth[j]:<9.4g} "
                f"median rel err={mre:7.4f}  2sig coverage={cov:5.2f}{mark}"
            )
        print()

    cen = censoring_study()
    model = cen["model"]
    print("  G1c' censoring: progressive truncation of the stress range")
    print("      " + f"{'retained':>9s} {'sigma_max':>10s} {'n':>4s}  "
          + "  ".join(f"{n:>12s}" for n in model.param_names) + "   ordered?")
    print(f"      {'full':>9s} {SIGMA.max():10.1f} {cen['full'].n_points:4d}  "
          + "  ".join(f"{'1.00x':>12s}" for _ in model.param_names))
    for row in cen["rows"]:
        infl = "  ".join(f"{v:11.2f}x" for v in row["inflation"])
        ok = "yes" if row["ordered"] else "NO"
        print(f"      {row['frac']:>8.0%} {row['sigma_max']:10.1f} {row['n']:4d}  {infl}   {ok}")
        if not row["ordered"]:
            failures.append(
                f"G1c': at {row['frac']:.0%} retained, stderr(phi_m) did not "
                f"inflate more than stderr(phi)"
            )

    print()
    if failures:
        print(f"GATE N2 FAIL ({len(failures)} problem(s)):")
        for f in failures:
            print("  " + f)
        return 1
    print("GATE N2 PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
