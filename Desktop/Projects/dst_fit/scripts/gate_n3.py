"""Gate N3 / G2: does the tool notice when the model is wrong, and stay quiet when it isn't?

The half that is easy to forget is the control. A misspecification detector that
flags everything passes the interesting half of this gate and is useless, so
both directions are pre-registered and both have to hold.

Pass conditions, fixed before the run:

  G2a  misspecification is caught: data generated by model A and fit with model B
       must come back not-usable (systematic residuals, or a degenerate
       parameter pair), for every A != B pair tested
  G2b  the control: data generated by model A and fit with model A must come
       back usable. A detector that fails this is measuring nothing
  G2c  false-positive rate: over 50 noise realisations of correctly specified
       data, the runs test may fire on no more than 5. Its alpha is 0.01, so the
       expected count is 0.5 and a bar of 5 leaves room for the residual
       structure that a nonlinear fit leaves behind even when the model is right

Run:  python scripts/gate_n3.py
Exit code is 0 only if every gate passes.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from dst_fit.fitting import fit_model, synthetic_curve  # noqa: E402
from dst_fit.identifiability import assess  # noqa: E402

NOISE = 0.02
SIGMA = np.logspace(-2, 3, 40)

TRUTH = {
    "wyart_cates": (0.52, 0.58, 5.0),
    "herschel_bulkley": (2.0, 1.5, 0.6),
    "ellis": (10.0, 0.05, 3.0, 1.4),
}

N_FALSE_POSITIVE_TRIALS = 50
FALSE_POSITIVE_MAX = 5


def run_pair(gen: str, fit_with: str, seed: int = 0):
    sigma, eta = synthetic_curve(gen, TRUTH[gen], SIGMA, noise=NOISE, seed=seed)
    try:
        r = fit_model(fit_with, sigma, eta, n_starts=6, seed=seed)
    except (RuntimeError, ValueError) as exc:
        return None, str(exc)
    return assess(r), ""


def main() -> int:
    failures: list[str] = []
    names = list(TRUTH)

    print("G2a/G2b: generate with the row model, fit with the column model\n")
    header = f"{'generated':>18s} | " + " | ".join(f"{n:>16s}" for n in names)
    print("  " + header)
    print("  " + "-" * len(header))

    for gen in names:
        cells = []
        for fit_with in names:
            a, err = run_pair(gen, fit_with)
            if a is None:
                cells.append(f"{'refused':>16s}")
                # A refusal to fit is a legitimate way to catch misspecification.
                if gen == fit_with:
                    failures.append(f"G2b: {gen} could not fit its own data: {err}")
                continue

            flags = []
            if not a.well_specified:
                flags.append("struct")
            if not a.identifiable:
                flags.append("degen")
            label = ",".join(flags) if flags else "usable"
            cells.append(f"{label:>16s}")

            if gen != fit_with and a.usable:
                failures.append(
                    f"G2a: {gen} data fit with {fit_with} came back usable "
                    f"(rmse {a.rmse_log:.3f}, runs p {a.runs_p:.3g})"
                )
            if gen == fit_with and not a.usable:
                failures.append(
                    f"G2b: {gen} on its own data came back {label} "
                    f"(rmse {a.rmse_log:.3f}, runs p {a.runs_p:.3g})"
                )
        print(f"  {gen:>18s} | " + " | ".join(cells))

    print("\n  verdict text, wyart_cates data fit with herschel_bulkley:")
    a, _ = run_pair("wyart_cates", "herschel_bulkley")
    if a is not None:
        for line in a.verdict().splitlines():
            print("      " + line)

    print("\n  verdict text, wyart_cates data fit with wyart_cates:")
    a, _ = run_pair("wyart_cates", "wyart_cates")
    if a is not None:
        for line in a.verdict().splitlines():
            print("      " + line)

    # ---- G2c ------------------------------------------------------------
    print(f"\nG2c: false positives over {N_FALSE_POSITIVE_TRIALS} correctly specified fits")
    for name in names:
        fired = 0
        n_ok = 0
        for seed in range(N_FALSE_POSITIVE_TRIALS):
            a, _ = run_pair(name, name, seed=seed)
            if a is None:
                continue
            n_ok += 1
            if not a.well_specified:
                fired += 1
        print(f"  {name:>18s}: runs test fired {fired}/{n_ok}")
        if fired > FALSE_POSITIVE_MAX:
            failures.append(
                f"G2c: {name}: runs test fired {fired}/{n_ok}, above {FALSE_POSITIVE_MAX}"
            )

    print()
    if failures:
        print(f"GATE N3 FAIL ({len(failures)} problem(s)):")
        for f in failures:
            print("  " + f)
        return 1
    print("GATE N3 PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
