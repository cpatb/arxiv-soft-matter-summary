"""make_figures.py — every figure for the polydisperse-jamming project.

House style, per the lab's standing preferences:
  * minimal text on the axes; the explanation lives in a sibling .md, never on the plot
  * linear axes start at ZERO, never at the data range; log only above a decade, said so
  * each figure saves .pdf + .png + the PLOTTED DATA as .csv, so every number in a
    figure traces to a file
  * a provenance header (script, git-ish stamp, input record count) goes in the csv

Regeneration is deterministic: run twice, the PNGs must be byte-identical. `--check`
does exactly that and reports any figure that is not.

Usage
-----
    python3 make_figures.py            # build
    python3 make_figures.py --check    # build, rebuild, compare md5
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import os
import sys
from datetime import datetime, timezone

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt   # noqa: E402
import numpy as np                # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
FIG = os.path.join(HERE, "figures")

# Deterministic output: matplotlib embeds a creation date in PDF/PNG metadata unless
# told not to, which would defeat the byte-identity check.
matplotlib.rcParams["pdf.compression"] = 0
matplotlib.rcParams["svg.hashsalt"] = "polydisperse-jamming"
matplotlib.rcParams["font.size"] = 9
matplotlib.rcParams["axes.linewidth"] = 0.8
matplotlib.rcParams["figure.dpi"] = 150

COL = ["#1b1b1b", "#0072b2", "#d55e00", "#009e73", "#cc79a7", "#56b4e9"]


def save(fig, name: str, data_rows: list[dict], note: str) -> None:
    os.makedirs(FIG, exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(FIG, f"{name}.{ext}"), bbox_inches="tight",
                    metadata={"CreationDate": None} if ext == "pdf" else None)
    plt.close(fig)
    if data_rows:
        fp = os.path.join(FIG, f"{name}.csv")
        with open(fp, "w", newline="", encoding="utf-8") as fh:
            fh.write(f"# {name} -- plotted data\n")
            fh.write(f"# generated by make_figures.py at "
                     f"{datetime.now(timezone.utc).isoformat()}\n")
            fh.write(f"# {note}\n")
            w = csv.DictWriter(fh, fieldnames=sorted(data_rows[0]))
            w.writeheader()
            w.writerows(data_rows)
    print(f"  wrote {name}.pdf/.png" + (f"/.csv ({len(data_rows)} rows)"
                                        if data_rows else ""))


def read_csv(path: str) -> list[dict]:
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as fh:
        rows = list(csv.DictReader(
            ln for ln in fh if not ln.startswith("#")))
    for r in rows:
        for k, v in list(r.items()):
            try:
                r[k] = float(v)
            except (TypeError, ValueError):
                pass
    return rows


# --------------------------------------------------------------------------
# F1 -- phi_J against polydispersity
# --------------------------------------------------------------------------
def fig_phiJ():
    """phi_J against realised CV, resolved by BOTH friction and PSD family.

    The first version merged the families into one series per mu_p, which put the
    lognormal and uniform CV = 0.5 points on the same line and produced a spurious dip.
    They are different distributions and must be different series.

    Series with fewer than two CV points (the mu_p = 1 and 3 friction anchors, run only
    at CV = 0) are drawn as isolated markers and labelled as anchors, not as trends.
    """
    rows = read_csv(os.path.join(OUT, "phase2_summary.csv"))
    if not rows:
        print("  F1 skipped: no phase2_summary.csv")
        return
    fig, ax = plt.subplots(figsize=(3.6, 2.9))
    out_rows = []
    style = {"lognormal": ("o", "-"), "uniform": ("s", "--")}
    ci = 0
    keys = sorted({(r["family"], r["mu_p"]) for r in rows},
                  key=lambda k: (k[1], k[0]))
    for fam, mu in keys:
        g = sorted([r for r in rows if r["mu_p"] == mu and r["family"] == fam],
                   key=lambda x: x["cv_real"])
        x = np.array([r["cv_real"] for r in g])
        y = np.array([r["phi_J"] for r in g])
        e = np.array([r.get("phi_J_sd", np.nan) for r in g], float)
        m, ls = style.get(fam, ("^", ":"))
        lab = rf"$\mu_p$={mu:g}, {fam}"
        if len(g) < 2:
            ax.errorbar(x, y, yerr=e, marker="*", ms=8, ls="none",
                        color=COL[ci % len(COL)], label=rf"$\mu_p$={mu:g} (anchor)")
        else:
            ax.errorbar(x, y, yerr=e, marker=m, ms=3.5, lw=1.2, ls=ls, capsize=2,
                        color=COL[ci % len(COL)], label=lab)
        ci += 1
        for r in g:
            out_rows.append({"family": fam, "mu_p": mu, "cv_real": r["cv_real"],
                             "phi_J": r["phi_J"], "phi_J_sd": r.get("phi_J_sd"),
                             "n_seeds": r.get("n_seeds")})
    ax.axhline(0.64, ls=":", lw=0.9, color="grey")
    ax.set_xlabel("CV (realised)")
    ax.set_ylabel(r"$\phi_J$")
    ax.set_xlim(0, None)
    ax.set_ylim(0, 0.75)          # linear axis starts at zero
    ax.legend(frameon=False, fontsize=6, loc="lower left", ncol=2)
    save(fig, "F1_phiJ_vs_cv", out_rows,
         "phi_J from the p_hat->0 extrapolation, by friction AND PSD family. "
         "Dotted line = frictionless RCP 0.64. Stars are single-CV friction anchors.")


# --------------------------------------------------------------------------
# F2 -- what a phi_J shift is worth, against what M1 is worth
# --------------------------------------------------------------------------
def fig_amplification():
    rows = read_csv(os.path.join(OUT, "phase2_summary.csv"))
    if not rows:
        print("  F2 skipped: no phase2_summary.csv")
        return
    # Endpoints must be taken WITHIN a family. Sorting all rows by cv_real mixes the
    # lognormal and uniform CV = 0.5 points, which differ by 0.039 -- the very effect
    # this project is measuring -- and silently picks whichever sorts last.
    keys = sorted({(r["family"], r["mu_p"]) for r in rows}, key=lambda k: (k[1], k[0]))
    fig, ax = plt.subplots(figsize=(3.6, 2.8))
    phi = np.linspace(0.0, 0.62, 400)
    out_rows = []
    for i, (fam, mu) in enumerate(keys):
        g = sorted([r for r in rows if r["mu_p"] == mu and r["family"] == fam],
                   key=lambda x: x["cv_real"])
        if len(g) < 2:
            continue
        lo, hi = g[0]["phi_J"], g[-1]["phi_J"]
        a, b = lo - phi, hi - phi
        ok = (a > 0) & (b > 0)
        ratio = np.where(ok, (a / np.where(ok, b, 1)) ** 2, np.nan)
        ax.plot(phi[ok], ratio[ok], lw=1.4,
                ls="-" if fam == "lognormal" else "--",
                color=COL[i % len(COL)],
                label=(rf"$\mu_p$={mu:g}, {fam}"
                       rf" (CV {g[0]['cv_real']:.2f}$\to${g[-1]['cv_real']:.2f})"))
        for p, r in zip(phi[ok][::20], ratio[ok][::20]):
            out_rows.append({"family": fam, "mu_p": mu, "phi": p,
                             "eta_ratio": r, "cv_lo": g[0]["cv_real"],
                             "cv_hi": g[-1]["cv_real"]})
    # Below 1 means polydispersity THINS the suspension at fixed phi.
    ax.axhline(1.0, ls=":", lw=0.8, color="grey")
    ax.axvline(0.44, ls="--", lw=0.9, color="grey")
    ax.set_xlabel(r"$\phi$")
    ax.set_ylabel(r"$\eta(\mathrm{high\ CV})\,/\,\eta(\mathrm{low\ CV})$")
    ax.set_xlim(0, 0.62)
    ax.set_ylim(0, 1.15)   # ratio is below 1: polydispersity THINS
    ax.legend(frameon=False, fontsize=5.5, loc="lower left")
    save(fig, "F2_amplification", out_rows,
         "eta(high CV)/eta(low CV) = ((phiJ_lo - phi)/(phiJ_hi - phi))^2. "
         "Below 1 = polydispersity thins. Dotted = no effect; dashed vertical "
         "= the lab's phi = 0.44")


# --------------------------------------------------------------------------
# F3 -- structure at matched mechanical state
# --------------------------------------------------------------------------
def fig_structure():
    rows = read_csv(os.path.join(OUT, "phase3_structure.csv"))
    if not rows:
        print("  F3 skipped: no phase3_structure.csv")
        return
    keys = ["z_all", "rattler_frac_k2", "z_nr_k2", "force_tail_slope"]
    labels = {"z_all": "$Z$ (all grains)",
              "rattler_frac_k2": "rattler fraction ($k$=2)",
              "z_nr_k2": "$Z$ (backbone, $k$=2)",
              "force_tail_slope": "force tail slope"}
    have = [k for k in keys if any(r["observable"] == k for r in rows)]
    if not have:
        print("  F3 skipped: no matching observables")
        return
    fig, axes = plt.subplots(1, len(have), figsize=(2.5 * len(have), 2.5))
    if len(have) == 1:
        axes = [axes]
    out_rows = []
    for ax, k in zip(axes, have):
        g = [r for r in rows if r["observable"] == k]
        x = np.arange(len(g))
        eff = np.array([r["effect"] for r in g])
        sd = np.array([r["seed_sd"] for r in g])
        ax.bar(x, eff, yerr=sd, color=COL[1], capsize=2, width=0.6)
        ax.axhline(0, lw=0.8, color="k")
        ax.set_xticks(x)
        ax.set_xticklabels([f"{r['p_hat']:.0e}" for r in g], fontsize=6,
                           rotation=45)
        ax.set_title(labels.get(k, k), fontsize=7)
        for r in g:
            out_rows.append(r)
    axes[0].set_ylabel("effect over CV range")
    fig.tight_layout()
    save(fig, "F3_structure_effects", out_rows,
         "bar = observable(CV_hi) - observable(CV_lo) at matched p_hat; "
         "error bar = seed sd")


# --------------------------------------------------------------------------
# F4 -- the boundary condition
# --------------------------------------------------------------------------
def fig_boundary():
    """Spread and backbone fraction across the three boundary conditions.

    The x-axis is CATEGORICAL, not numeric. `caged` is Lambda = 0 and `free` is
    Lambda = infinity; neither is a number that can sit on a log axis. The first
    version placed them at sentinel positions 1e-3 and 1e9, which produced a
    twelve-decade axis that squashed the real capillary trend (0.99 -> 1.06 -> 1.31)
    into a few pixels and implied a spacing that does not exist. Ordered categories
    say exactly what was run and nothing more.
    """
    import glob
    import json
    recs = []
    for f in glob.glob(os.path.join(OUT, "phase4*.jsonl")):
        with open(f, encoding="utf-8") as fh:
            for line in fh:
                try:
                    r = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if not r.get("failed") and not r.get("exploded"):
                    recs.append(r)
    if not recs:
        print("  F4 skipped: no phase4 records")
        return

    def cat(r):
        if r["bc"] == "caged":
            return "caged"
        if r["bc"] == "free":
            return "free"
        return "cap {:g}".format(r["lam"])

    def order(r):
        return {"caged": -1.0, "free": 1e18}.get(r["bc"], float(r["lam"]))

    cats = sorted({cat(r) for r in recs},
                  key=lambda c: min(order(r) for r in recs if cat(r) == c))
    xpos = {c: i for i, c in enumerate(cats)}

    fig, axes = plt.subplots(1, 2, figsize=(6.6, 2.8))
    out_rows = []
    groups: dict[tuple, list[dict]] = {}
    for r in recs:
        groups.setdefault((r["cv"], cat(r)), []).append(r)

    for i, cv in enumerate(sorted({r["cv"] for r in recs})):
        xs, y1, e1, y2, e2 = [], [], [], [], []
        for c in cats:
            g = groups.get((cv, c))
            if not g:
                continue
            sp = np.array([x["spread"] for x in g], float)
            bb = np.array([x["largest_frac_peak"] for x in g], float)
            xs.append(xpos[c])
            y1.append(float(np.nanmean(sp)))
            e1.append(float(np.nanstd(sp)))
            y2.append(float(np.nanmean(bb)))
            e2.append(float(np.nanstd(bb)))
            out_rows.append({"cv": cv, "boundary": c, "n": len(g),
                             "spread_mean": float(np.nanmean(sp)),
                             "spread_sd": float(np.nanstd(sp)),
                             "largest_frac_mean": float(np.nanmean(bb))})
        if not xs:
            continue
        axes[0].errorbar(xs, y1, yerr=e1, marker="o", ms=4, lw=1.2, capsize=2,
                         color=COL[i % len(COL)], label=f"CV = {cv:g}")
        axes[1].errorbar(xs, y2, yerr=e2, marker="s", ms=4, lw=1.2, capsize=2,
                         color=COL[i % len(COL)])
    for ax in axes:
        ax.set_xticks(range(len(cats)))
        ax.set_xticklabels(cats, fontsize=6, rotation=30)
        ax.set_xlim(-0.4, len(cats) - 0.6)
        ax.set_xlabel(r"boundary condition (increasing $\Lambda$)")
    axes[0].set_ylabel("lateral spread")
    axes[1].set_ylabel("largest backbone fraction")
    axes[0].set_ylim(0, None)
    axes[1].set_ylim(0, 1.1)
    axes[0].legend(frameon=False, fontsize=6)
    fig.tight_layout()
    save(fig, "F4_boundary_condition", out_rows,
         "Boundary conditions in order of confinement strength. The axis is "
         "CATEGORICAL: caged is Lambda=0 and free is Lambda=infinity, neither of "
         "which is a plottable number. Spacing carries no meaning.")


def md5(path: str) -> str:
    with open(path, "rb") as fh:
        return hashlib.md5(fh.read()).hexdigest()


def build():
    for f in (fig_phiJ, fig_amplification, fig_structure, fig_boundary):
        try:
            f()
        except Exception as exc:      # noqa: BLE001
            print(f"  {f.__name__} FAILED: {exc!r}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="build twice and require byte-identical PNGs")
    args = ap.parse_args()

    print("building figures...")
    build()
    if not args.check:
        return 0

    import glob
    before = {p: md5(p) for p in sorted(glob.glob(os.path.join(FIG, "*.png")))}
    print("rebuilding for the byte-identity check...")
    build()
    after = {p: md5(p) for p in sorted(glob.glob(os.path.join(FIG, "*.png")))}
    bad = [p for p in before if before[p] != after.get(p)]
    for p in sorted(before):
        tag = "DIFFERS" if p in bad else "identical"
        print(f"  {os.path.basename(p):32s} {tag}")
    if bad:
        print(f"REGENERATION CHECK FAILED for {len(bad)} figure(s)")
        return 1
    print(f"REGENERATION CHECK PASSED for {len(before)} figure(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
