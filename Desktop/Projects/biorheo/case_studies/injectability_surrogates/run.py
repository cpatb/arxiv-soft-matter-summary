"""Case study 1: needle injectability of two Carbopol surrogates from the registry.

Two deposited flow curves (doi:10.25835/hjn2qcvy, ETD2020, 20 C, smooth plates):
``carbopol_etd2020_0p5wt_50uL`` (tau_y = 41 Pa, yield-dominated) and
``carbopol_etd2020_0p1wt_40uL`` (tau_y = 0.8 Pa, thinning-dominated). Each is refitted
here with ``biorheo.identify`` exactly as ``scripts/identify_carbopol.py`` does, so the
force carries the profile intervals and covariance of that fit, and the plunger force
is computed at three dose rates through one needle.

Inputs that are choices, not measurements: needle inner radius 0.10 mm, length 25 mm,
barrel radius 2.3 mm, dose 1 mL over 30 / 10 / 3 s, density 1000 kg/m^3 for the
Reynolds number, no friction term. Replace them with the device datasheet; nothing
below depends on their being "right", only on their being stated.

Writes ``results.md`` and ``force_vs_Q.png`` beside this file. Run from anywhere:

    python case_studies/injectability_surrogates/run.py
"""

from __future__ import annotations

import hashlib
import io
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.integrate import quad

from biorheo.apps import Needle, Syringe, force_with_uq, wall_stress
from biorheo.apps.injectability import _shear_rate_at_stress
from biorheo.constitutive import get_model
from biorheo.identify import fit_rate_curve
from biorheo.registry import load_all

HERE = Path(__file__).resolve().parent
DATA = HERE.parents[2] / "carbopol" / "data" / "etd2020_biermann2024"
HB = get_model("herschel_bulkley")

NEEDLE = Needle(radius=0.10e-3, length=25e-3)   # m; illustrative, see docstring
SYRINGE = Syringe(barrel_radius=2.3e-3)         # m; illustrative
DOSE_ML, DOSE_TIMES_S = 1.0, (30.0, 10.0, 3.0)
RHO = 1000.0                                    # kg/m^3, assumed for Re only
LAMINAR_RE = 2100.0                             # Newtonian pipe transition; the only threshold used
SURROGATES = {
    "carbopol_etd2020_0p5wt_50uL": "ETD2020-05wt-50ul.csv",
    "carbopol_etd2020_0p1wt_40uL": "ETD2020-01wt-40ul.csv",
}


def load(path: Path) -> tuple[np.ndarray, np.ndarray]:
    """(recovered rate, mean stress), the same reader as scripts/identify_carbopol.py."""
    raw = io.open(path, encoding="latin-1").read().splitlines()
    rows = [r.split(";") for r in raw[2:] if r.strip()]
    num = lambda c: float(c.replace(",", ".")) if c.strip() else np.nan
    a = np.array([[num(c) for c in r] for r in rows])
    tau = a[:, [2, 4, 6]]
    eta = a[:, [3, 5, 7]] * 1e-3
    return np.nanmean(tau / eta, axis=1), np.nanmean(tau, axis=1)


def flow_fraction_outside_envelope(dp: float, params, gd_max: float) -> float:
    """Fraction of Q carried by radii where the local shear rate exceeds ``gd_max``,
    i.e. the share of the flow that rests on extrapolated rheology."""
    R, L = NEEDLE.radius, NEEDLE.length
    tw = wall_stress(dp, R, L)

    def gd_at(r):
        return _shear_rate_at_stress(HB, params, tw * r / R)

    if gd_at(R) <= gd_max:
        return 0.0
    # radius where the local rate equals gd_max: tau = tau_y + k gd_max^n
    tau_y, k, n = params
    r_star = R * (tau_y + k * gd_max ** n) / tw
    inner, _ = quad(lambda r: r * r * gd_at(r), 0.0, r_star, limit=200)
    outer, _ = quad(lambda r: r * r * gd_at(r), r_star, R, limit=200)
    return outer / (inner + outer)


def main() -> None:
    records = load_all(allow_network=False)
    md = ["# Needle injectability of two Carbopol surrogates", "",
          "Generated by `run.py`; every number here is reproduced by running it. Inputs "
          "that are choices (needle, syringe, dose, density) are listed in the script's "
          "docstring and are not measurements.", "",
          f"Needle R = {NEEDLE.radius * 1e3:.2f} mm, L = {NEEDLE.length * 1e3:.0f} mm; barrel "
          f"R = {SYRINGE.barrel_radius * 1e3:.1f} mm; dose {DOSE_ML:g} mL.", ""]
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 3.0), sharey=False)
    summary = {}
    for ax, (rid, csv) in zip(axes, SURROGATES.items()):
        rec = records[rid]
        g, t = load(DATA / csv)
        good = np.isfinite(g) & np.isfinite(t) & (g > 0) & (t > 0)
        print(f"{rid}: N = {g.size} -> {good.sum()} after finite/positive mask")
        ident = fit_rate_curve(HB, g[good], t[good] / g[good],
                               temperature_C=rec.envelope.temperature_C, geometry=rec.envelope.geometry)
        dev = np.max(np.abs(ident.values / rec.params_si - 1.0))
        md += [f"## `{rid}`", "",
               f"Refit: tau_y = {ident.values[0]:.5g} Pa, k = {ident.values[1]:.5g} Pa s^n, "
               f"n = {ident.values[2]:.5g} (five figures: d ln F / d ln n reaches 7, so three "
               f"would not let a reader reproduce the table to 1 %); within {dev:.1%} of the "
               f"registry record. Fitted "
               f"envelope [{ident.envelope.gammadot_min:.3g}, {ident.envelope.gammadot_max:.3g}] 1/s.", "",
               "| dose time (s) | Q (mL/s) | F (N) | one-at-a-time profile envelope 95 % (N) | covariance 95 % (N) | dp (bar) | gd_w (1/s) | Re | plug r_p/R | Q share outside envelope | extrapolated |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
        Qs, Fs, plo, phi, slo, shi = [], [], [], [], [], []
        mid = None
        for t_dose in DOSE_TIMES_S:
            Q = DOSE_ML * 1e-6 / t_dose
            uq = force_with_uq(ident, Q, NEEDLE, SYRINGE, rho=RHO)
            share = flow_fraction_outside_envelope(uq.nominal.dp, ident.values, ident.envelope.gammadot_max)
            n_ = uq.nominal
            md.append(f"| {t_dose:g} | {Q * 1e6:.3g} | {n_.force:.3f} | [{uq.profile_lo:.3f}, {uq.profile_hi:.3f}] | "
                      f"[{uq.sampled_lo:.3f}, {uq.sampled_hi:.3f}] | {n_.dp / 1e5:.3f} | {n_.wall_shear_rate:.3g} | "
                      f"{n_.reynolds:.2g} | {n_.plug_fraction:.3f} | {share:.1%} | "
                      f"{'YES' if uq.extrapolated else 'no'} |")
            Qs.append(Q); Fs.append(n_.force); plo.append(uq.profile_lo); phi.append(uq.profile_hi)
            slo.append(uq.sampled_lo); shi.append(uq.sampled_hi)
            if t_dose == DOSE_TIMES_S[1]:
                mid = uq
        assert mid is not None
        summary[rid] = (mid, ident)
        md += ["",
               f"Sensitivity d ln F / d ln p at {DOSE_TIMES_S[1]:g} s: "
               + ", ".join(f"{k} {v:+.3f}" for k, v in mid.sensitivity.items())
               + f". Insensitive to: {', '.join(mid.insensitive_to) or 'none'}.", ""]
        md += [f"- {n}" for n in mid.notes] + ([""] if mid.notes else [])
        Qs = np.array(Qs) * 1e6
        ax.fill_between(Qs, plo, phi, color="0.85", lw=0)
        ax.fill_between(Qs, slo, shi, color="0.6", lw=0)
        ax.plot(Qs, Fs, "k.-")
        ax.set_xlim(0, None); ax.set_ylim(0, None)
        ax.set_xlabel("Q (mL/s)"); ax.set_ylabel("F (N)")
    fig.tight_layout()
    png = HERE / "force_vs_Q.png"
    fig.savefig(png, dpi=200, metadata={"Software": None})
    # --- what the numbers say, computed rather than typed -----------------------------
    (rid_a, (a, ia)), (rid_b, (b, ib)) = summary.items()
    dec_a = np.log10(a.nominal.wall_shear_rate / ia.envelope.gammadot_max)
    dec_b = np.log10(b.nominal.wall_shear_rate / ib.envelope.gammadot_max)
    ratio = b.nominal.force / a.nominal.force
    sig_a = ia.model.stress(a.nominal.wall_shear_rate, *ia.values)
    sig_b = ib.model.stress(b.nominal.wall_shear_rate, *ib.values)
    # the deposited curves at their own top rate, where the data still exists
    top = min(ia.envelope.gammadot_max, ib.envelope.gammadot_max)
    sig_a_top = ia.model.stress(top, *ia.values)
    sig_b_top = ib.model.stress(top, *ib.values)
    plug_max = max(a.nominal.plug_fraction, b.nominal.plug_fraction)
    sep_1e5 = ib.model.stress(1e5, *ib.values) / ia.model.stress(1e5, *ia.values)
    re_max = max(uq.nominal.reynolds for uq, _ in summary.values())  # the 10 s dose
    fast = [force_with_uq(i_, DOSE_ML * 1e-6 / DOSE_TIMES_S[-1], NEEDLE, SYRINGE, rho=RHO).nominal
            for _, i_ in summary.values()]
    re_3s = max(f.reynolds for f in fast)
    gdw_3s = max(f.wall_shear_rate for f in fast)
    assert re_3s < LAMINAR_RE, f"Re = {re_3s:.0f} at the 3 s dose is not below {LAMINAR_RE}"
    md += ["## Reading", "",
           f"1. Every force above is an extrapolation of the rheometry: the wall shear rate is "
           f"{dec_a:.1f} decades ({rid_a}) and {dec_b:.1f} decades ({rid_b}) above the top of the "
           f"deposited flow curves at the {DOSE_TIMES_S[1]:g} s dose, and essentially all of Q "
           f"is carried there. The profile and covariance intervals are conditional on "
           f"Herschel-Bulkley holding over those decades, which the data does not test; they "
           f"bound the parameter uncertainty, not the model-form uncertainty.", "",
           f"2. The ordering of the two surrogates flips between the rheometer and the needle. At "
           f"the top of the measured range ({top:g} 1/s) the stresses are {sig_a_top:.0f} Pa "
           f"({rid_a}) and {sig_b_top:.0f} Pa ({rid_b}); at the needle wall the fitted curves give "
           f"{sig_a:.0f} Pa and {sig_b:.0f} Pa, so the LOWER-concentration gel needs {ratio:.1f}x "
           f"the force. That comes entirely from the flow index (n = {ia.values[2]:.3f} against "
           f"{ib.values[2]:.3f}) carried {max(dec_a, dec_b):.1f} decades past the data. Which surrogate is harder "
           f"to inject through this needle is not decided by the deposited measurements.", "",
           f"3. The force is insensitive to the yield stress for both gels "
           f"(d ln F / d ln tau_y = {a.sensitivity['tau_y']:+.3f} and {b.sensitivity['tau_y']:+.3f}): "
           f"the plug is at most {plug_max:.1%} of the radius. Injectability of these surrogates "
           f"is a high-rate consistency question. The measurement that would settle the "
           f"ORDERING is a capillary or slit rheometer run to 1e5 1/s (the curves are "
           f"{sep_1e5:.1f}x apart there); the force MAGNITUDE at the 3 s dose needs the wall "
           f"rate itself, {gdw_3s:.2g} 1/s. Not a better yield-stress fit.", "",
           f"4. Reynolds numbers (rho U 2R / eta at the wall rate) reach {re_max:.0f} at the "
           f"{DOSE_TIMES_S[1]:g} s dose and {re_3s:.0f} at 3 s, below the Newtonian transition "
           f"{LAMINAR_RE:g}, the only threshold used: laminar, but the entrance and exit "
           f"losses left out of the closed form grow with Re and are not in these numbers.", "",
           f"5. No slip. Carbopol slips on smooth walls at stresses far below the "
           f"{max(sig_a, sig_b) / 1e3:.0f} kPa the needle wall sees, so every force above is an "
           f"upper bound in that respect; the deposited data (smooth plates, one gap) cannot "
           f"say by how much. A two-radius needle test at matched wall stress would.", "",
           f"6. The Herschel-Bulkley form is not exact for either curve within the data: the "
           f"log residuals ordered by rate have {ia.residual_structure.n_runs} runs where "
           f"{ia.residual_structure.expected_runs:.0f} are expected ({rid_a}, rmse_log "
           f"{ia.fit.rmse_log:.3f}) and {ib.residual_structure.n_runs} where "
           f"{ib.residual_structure.expected_runs:.0f} are expected ({rid_b}, rmse_log "
           f"{ib.fit.rmse_log:.3f}; signs `{ib.residual_structure.signs}`). For the 0.5 wt% gel "
           f"that is a {ia.fit.rmse_log:.1%} systematic misfit; for the 0.1 wt% gel it is "
           f"{ib.fit.rmse_log:.0%}, so the "
           f"flow index carried past the data in point 2 is the index of a form that already "
           f"misses this curve by that much.", "",
           "## Figure", "",
           "`force_vs_Q.png`: plunger force against dose rate, left the 0.5 wt% and right the "
           "0.1 wt% surrogate. Light band: one-at-a-time profile interval; dark band: covariance "
           "sample; points: the fit. Both axes start at zero.", "",
           f"png md5: `{hashlib.md5(png.read_bytes()).hexdigest()}`", ""]
    (HERE / "results.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
