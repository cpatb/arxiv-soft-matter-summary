"""Item 28 pins: which shipped conclusions survive a non-zero syringe friction term.

The artifact is `case_studies/device_friction/results.json`, generated by the sibling
`run.py` from the SHIPPED case-study JSONs. These tests read the artifact; they do not
regenerate it, so a failure here cannot destroy the reference it is checking against.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "case_studies" / "device_friction" / "results.json"
MD = ROOT / "case_studies" / "device_friction" / "results.md"
PREREG = ROOT / "case_studies" / "device_friction" / "prereg.md"


@pytest.fixture(scope="module")
def art() -> dict:
    assert ART.exists(), f"missing artifact {ART}; run case_studies/device_friction/run.py"
    return json.loads(ART.read_text(encoding="utf-8"))


def test_c1_reproduces_all_three_shipped_numbers(art):
    """C1 is the only check that certifies the re-implementation. Without it no number
    in this study is believable, so it is asserted first and in full."""
    c1 = art["C1_reproduction"]
    assert c1["pass"]
    assert c1["ratio_recomputed"] == pytest.approx(c1["ratio_shipped"], abs=1e-12)
    assert (c1["mab_disjoint_recomputed"], c1["mab_pairs_recomputed"]) == (1525, 1653)
    assert (c1["blood_disjoint_recomputed"], c1["blood_pairs_recomputed"]) == (36, 190)
    # and it must not be vacuous: the shipped values have to have been READ, not assumed
    assert c1["mab_disjoint_shipped"] == 1525
    assert c1["ratio_shipped"] == pytest.approx(7.052465, abs=5e-6)


def test_the_invariants_are_recorded_as_arithmetic_not_as_gates(art):
    """Order, differences and deterministic separability are invariant under an additive
    constant BY CONSTRUCTION. They are checked so the claim is auditable, and they are
    deliberately not counted among the pre-registered gates: a check that cannot fail
    decides nothing."""
    inv = art["invariants_by_construction"]
    assert inv["order_preserved"]
    assert inv["differences_preserved"]
    assert inv["deterministic_separability_preserved"]
    assert inv["probe_N"] > 0


def test_the_ratio_claim_is_a_property_of_friction_being_zero(art):
    q1 = art["Q1_constant_friction"]
    assert q1["ratio_at_f"]["0"] == pytest.approx(7.052465, abs=5e-6)
    # P1 and P2 as pre-registered
    assert q1["ratio_at_f"]["1"] < 3.0
    assert q1["ratio_at_f"]["3"] < 2.0
    assert q1["f_first_below_2"] < 4.0
    assert q1["P1_pass"] and q1["P2_pass"]
    # the DIFFERENCE is what survives, and it must be the shipped one
    assert q1["median_difference_N"] == pytest.approx(
        q1["median_mab_N"] - q1["median_blood_N"], rel=1e-12)


def test_the_screen_threshold_and_that_p3_is_recorded_refuted(art):
    """P3 predicted s* < 0.05 N and the measured threshold is 0.1397 N. The bar was not
    moved; the artifact must still carry the FAILED verdict beside the number."""
    q2 = art["Q2_friction_repeatability"]
    assert q2["P3_pass"] is False, "P3 was refuted; a PASS here means the bar moved"
    assert q2["mab"]["s_star_50pct_N"] == pytest.approx(0.1397, rel=2e-3)
    assert q2["mab"]["frac_at_s0"] == pytest.approx(1525 / 1653, rel=1e-12)
    assert q2["blood"]["frac_at_s0"] == pytest.approx(36 / 190, rel=1e-12)
    # the threshold must be a real crossing, not the end of the grid
    assert 0.0 < q2["mab"]["s_star_50pct_N"] < 5.0


def test_p4_is_refuted_and_its_matched_convention_companion_is_labelled_post_hoc(art):
    p4 = art["P4_which_cohort_is_exposed"]
    assert p4["pass"] is False, "P4 was refuted; a PASS here means the bar moved"
    assert p4["mab_growth"] > 3.0          # the half of P4 that held
    assert p4["blood_growth"] > 1.3        # the half that did not
    mc = p4["matched_convention"]
    assert "POST-HOC" in mc["status"]
    # direction right, size wrong: the mAb cohort is more exposed, but by ~1.8x not ~3.5x
    assert mc["mab_over_blood"] > 1.0
    assert mc["mab_over_blood"] < 3.5


def test_the_null_did_not_fire_and_is_recorded_either_way(art):
    """C4: had s* exceeded 1 N the honest verdict would be 'friction is irrelevant here'.
    The artifact records the test regardless of which way it came out."""
    c4 = art["C4_null"]
    assert "would_fire_if" in c4
    assert c4["fired"] is False


def test_no_friction_magnitude_is_asserted_anywhere_in_the_deliverable():
    """C3: this study quotes a THRESHOLD, never a device's friction. A number smuggled in
    from memory or from an unresolved source is the failure mode this guards."""
    md = MD.read_text(encoding="utf-8")
    assert "No friction magnitude is asserted here" in md
    assert "Nothing here measures a syringe" in md
    # the one external magnitude admitted must be ATTRIBUTED, with a DOI on the page
    assert "doi:10.1002/jps.23945" in md


def test_the_external_placement_is_attributed_and_names_its_own_gap(art):
    """The Q1 side gets an external anchor; the Q2 side has none, because the survey
    resolved friction MEANS and no friction SD for any device. That gap is the reason s*
    is quoted as a threshold, and it must be stated on the page rather than left to be
    inferred."""
    e = art["external_placement"]
    assert "doi:" in e["source"]
    assert e["no_repeatability_resolved"] is True
    assert "unpublished" in e["gap"]
    # the device is not the one the case studies specify, and the page must say so
    assert "CHOICE" in e["device"]
    # at a published glide friction the shipped 7.05x ratio is around 2x
    lo, hi = e["ratio_at_glide"]
    assert 1.8 < hi < lo < 2.3
    md = MD.read_text(encoding="utf-8")
    assert "no comparator at all" in md


def test_the_prereg_records_the_refutations_in_an_addendum_not_by_editing():
    """A pre-registration is never rewritten in this repo."""
    txt = PREREG.read_text(encoding="utf-8")
    assert "## Addendum A" in txt
    assert "P3 REFUTED" in txt and "P4 REFUTED" in txt
    assert "no bar was moved" in txt.lower()
    # the body's original P3 bar must still be there, unedited
    assert "below 50 % at some s* < 0.05 N" in txt
