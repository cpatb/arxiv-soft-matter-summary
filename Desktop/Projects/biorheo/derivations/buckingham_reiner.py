"""SymPy derivation of Herschel-Bulkley flow through a circular needle, for
``biorheo.apps.injectability``.

Fully developed laminar flow of a fluid with ``sigma = tau_y + k gd^n`` (gd > 0) in a
tube of radius ``R`` and length ``L`` under a pressure drop ``dp``. Momentum balance
gives the stress profile ``tau(r) = dp r / (2 L)`` independent of the fluid; the wall
stress is ``tau_w = dp R / (2 L)`` and the unyielded plug has radius
``r_p = R tau_y / tau_w = 2 tau_y L / dp``. Integrating by parts with ``u(R) = 0``,

    Q = 2 pi int_0^R r u dr = pi int_{r_p}^R r^2 gd(r) dr,    gd = ((tau - tau_y)/k)^(1/n).

Changing variable to ``s = tau - tau_y`` gives a closed form for every ``n`` (Skelland's
form; the Buckingham-Reiner equation is its n = 1 case):

    Q = pi R^3 / tau_w^3 * k^(-1/n) * [ S^(1/n+3)/(1/n+3) + 2 tau_y S^(1/n+2)/(1/n+2)
                                        + tau_y^2 S^(1/n+1)/(1/n+1) ],   S = tau_w - tau_y,

valid for ``tau_w > tau_y``; ``Q = 0`` otherwise. Everything the module computes is
checked here against that integral, its three named limits and hand-evaluated spots.

Run:  python derivations/buckingham_reiner.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import sympy as sp

r, R, L, dp, tau_y, k, n, mu, s = sp.symbols("r R L Delta_p tau_y k n mu s", positive=True)
tau_w = dp * R / (2 * L)
r_p = 2 * tau_y * L / dp

OUT = Path(__file__).with_name("buckingham_reiner.md")
lines: list[str] = ["# Herschel-Bulkley needle flow (SymPy, generated by `buckingham_reiner.py`)", ""]
failures = 0


def check(title: str, got, expected):
    global failures
    ok = sp.simplify(got - expected) == 0
    failures += 0 if ok else 1
    lines.append(f"- {'PASS' if ok else 'FAIL'} **{title}**: `{sp.sstr(sp.simplify(got))}` "
                 f"{'==' if ok else '!='} `{sp.sstr(sp.simplify(expected))}`")


def spot(title: str, expr, values: dict, expected: float, rel=1e-6):
    global failures
    got = float(expr.subs(values).evalf())
    ok = abs(got - expected) <= rel * abs(expected)
    failures += 0 if ok else 1
    lines.append(f"- {'PASS' if ok else 'FAIL'} spot {title}: {got:.7g} vs hand {expected:.7g}")


# --- the integral, done by SymPy in the stress variable ------------------------------
# tau = tau_w r / R  ->  r = R tau / tau_w, dr = (R / tau_w) dtau; then s = tau - tau_y
S = tau_w - tau_y
integrand = (s + tau_y) ** 2 * (s / k) ** (1 / n)
Q_int = sp.pi * (R / tau_w) ** 3 * sp.integrate(integrand, (s, 0, S))
Q_closed = sp.pi * R ** 3 / tau_w ** 3 * k ** (-1 / n) * (
    S ** (1 / n + 3) / (1 / n + 3) + 2 * tau_y * S ** (1 / n + 2) / (1 / n + 2)
    + tau_y ** 2 * S ** (1 / n + 1) / (1 / n + 1))

lines += ["## Definitions", "",
          f"- wall stress `tau_w = {sp.sstr(tau_w)}`, plug radius `r_p = {sp.sstr(r_p)}`",
          "- `Q = pi int_{r_p}^R r^2 gd(r) dr` with `gd = ((tau - tau_y)/k)^(1/n)`, "
          "`tau = tau_w r/R`", "",
          "## Results", ""]

check("closed form equals the integral for general n", Q_int, Q_closed)

# --- limits --------------------------------------------------------------------------
newt = sp.pi * R ** 4 * dp / (8 * mu * L)
check("Newtonian (tau_y = 0, n = 1, k = mu): Q = pi R^4 dp / (8 mu L)",
      Q_closed.subs({tau_y: 0, n: 1, k: mu}), newt)

pl = sp.pi * n / (3 * n + 1) * R ** 3 * (dp * R / (2 * k * L)) ** (1 / n)
check("power law (tau_y = 0): Q = pi n/(3n+1) R^3 (dp R/(2 k L))^(1/n)",
      Q_closed.subs(tau_y, 0), pl)

phi = r_p / R  # = tau_y / tau_w
bingham = sp.pi * R ** 4 * dp / (8 * mu * L) * (1 - sp.Rational(4, 3) * phi + phi ** 4 / 3)
check("Bingham (n = 1, k = mu): Buckingham-Reiner pi R^4 dp/(8 mu L) [1 - 4/3 phi + 1/3 phi^4]",
      Q_closed.subs({n: 1, k: mu}), bingham)

check("Q -> 0 as tau_w -> tau_y (plug fills the tube)",
      sp.limit(Q_closed.subs({n: 1, k: mu}), dp, 2 * tau_y * L / R, "+"), 0)

# wall shear rate, used by the module's extrapolation flag
gd_w = ((tau_w - tau_y) / k) ** (1 / n)
check("Newtonian wall shear rate 4 Q / (pi R^3)",
      gd_w.subs({tau_y: 0, n: 1, k: mu}), 4 * newt / (sp.pi * R ** 3))

# --- hand spots ----------------------------------------------------------------------
# Newtonian, three parameter sets (all SI):
#  (a) R = 1e-4 m, L = 0.02 m, mu = 1 Pa s, dp = 1e5 Pa:
#      pi * 1e-16 * 1e5 / (8 * 1 * 0.02) = pi * 1e-11 / 0.16 = 1.9634954e-10 m^3/s
#  (b) R = 2e-4, L = 0.04, mu = 0.1, dp = 5e4:
#      pi * 1.6e-15 * 5e4 / (8 * 0.1 * 0.04) = pi * 8e-11 / 0.032 = 7.8539816e-9
#  (c) R = 5e-5, L = 0.01, mu = 10, dp = 1e6:
#      pi * 6.25e-18 * 1e6 / (8 * 10 * 0.01) = pi * 6.25e-12 / 0.8 = 2.4543693e-11
spot("Newtonian (a)", newt, {R: 1e-4, L: 0.02, mu: 1.0, dp: 1e5}, 1.9634954e-10)
spot("Newtonian (b)", newt, {R: 2e-4, L: 0.04, mu: 0.1, dp: 5e4}, 7.8539816e-9)
spot("Newtonian (c)", newt, {R: 5e-5, L: 0.01, mu: 10.0, dp: 1e6}, 2.4543693e-11)

# power law: R = 1e-4, L = 0.02, k = 2, n = 0.5, dp = 1e5
#   tau_w = 1e5 * 1e-4 / 0.04 = 250 Pa; (tau_w/k)^(1/n) = 125^2 = 15625 1/s
#   n/(3n+1) = 0.5/2.5 = 0.2;  Q = pi * 0.2 * 1e-12 * 15625 = pi * 3.125e-9 = 9.8174770e-9
spot("power law n = 0.5", pl, {R: 1e-4, L: 0.02, k: 2.0, n: 0.5, dp: 1e5}, 9.8174770e-9)

# Bingham: R = 1e-4, L = 0.02, mu = 1, dp = 1e5, tau_y = 50 Pa
#   tau_w = 250 Pa, phi = 0.2; bracket = 1 - 0.2666667 + 0.0005333 = 0.7338667
#   Q = 1.9634954e-10 * 0.7338667 = 1.4409440e-10
spot("Bingham phi = 0.2", bingham, {R: 1e-4, L: 0.02, mu: 1.0, dp: 1e5, tau_y: 50.0}, 1.4409440e-10)
# and the general closed form at the same point must agree
spot("general closed form at the Bingham point", Q_closed,
     {R: 1e-4, L: 0.02, k: 1.0, n: 1, dp: 1e5, tau_y: 50.0}, 1.4409440e-10)

# HB, n = 0.5: R = 1e-4, L = 0.02, k = 2, n = 0.5, dp = 1e5, tau_y = 50
#   S = 200; 1/n = 2: terms 200^5/5 + 2*50*200^4/4 + 2500*200^3/3
#   = 6.4e10 + 4.0e10 + 6.6666667e9 = 1.1066667e11; k^-2 = 0.25 -> 2.7666667e10
#   pi R^3 / tau_w^3 = pi * 1e-12 / 1.5625e7 = 2.0106193e-19
#   Q = 2.0106193e-19 * 2.7666667e10 = 5.5627134e-9
spot("Herschel-Bulkley n = 0.5, tau_y = 50 Pa", Q_closed,
     {R: 1e-4, L: 0.02, k: 2.0, n: 0.5, dp: 1e5, tau_y: 50.0}, 5.5627134e-9)

lines += ["", f"**{failures} failure(s).**"]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print("\n".join(lines))
sys.exit(1 if failures else 0)
