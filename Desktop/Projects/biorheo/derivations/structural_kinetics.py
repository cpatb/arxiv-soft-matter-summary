"""SymPy derivation for the structural (thixotropic) family in
``biorheo.constitutive.structural``.

Source: ``Desktop/Projects/bio_fluids_bridge/blood_rheology.py`` (Moore / Coussot
lineage), which writes the kinetics as ``dlam/dt = k_build (1 - lam) - k_break gd lam``
and the viscosity as ``eta = eta_inf (1 + (eta_0/eta_inf - 1) lam)``. Here the same
model is written with ``t_r = 1/k_build`` (rebuild time), ``alpha = k_break`` (breakdown
per unit strain) and ``beta = eta_0/eta_inf - 1`` (structural viscosity gain).

Derived and checked below, writing ``structural_kinetics.md`` beside this file:

1. steady state ``lam_ss = 1/(1 + alpha t_r gd)``: alpha and t_r enter ONLY as the
   product, so a steady flow curve cannot separate them (the identify gate relies on
   this);
2. the steady viscosity IS the Cross model with ``m = 1``, ``eta_0 = eta_inf (1 + beta)``
   and ``lam_cross = alpha t_r``: nothing in a steady flow curve says "structural";
3. step response at constant rate: ``lam(t) = lam_ss + (lam0 - lam_ss) exp(-t/tau)``
   with ``1/tau = 1/t_r + alpha gd``: the transient is what carries t_r on its own;
4. the source's constants map to ``alpha t_r = 1/gamma_c = 0.2 s`` and ``beta = 56.142857``;
5. with the product ``a = alpha t_r`` fixed by the steady curve, the step relaxation time
   at rate gd gives ``t_r = tau (1 + a gd)`` and ``alpha = a/t_r`` on their own; the 95 %
   approach time is ``tau ln 20``; and the stress after a step from gd_0 to gd_1 is
   ``gd_1 eta_inf (1 + beta lam(t))`` with ``lam0 = lam_ss(gd_0)`` (used by
   ``scripts/structural_step_horner.py``).

Run:  python derivations/structural_kinetics.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import sympy as sp

t, gd, alpha, t_r, beta, eta_inf, lam0 = sp.symbols(
    "t gammadot alpha t_r beta eta_inf lambda_0", positive=True)
lam = sp.Function("lambda")(t)

OUT = Path(__file__).with_name("structural_kinetics.md")
lines: list[str] = ["# Structural kinetics (SymPy, generated by `structural_kinetics.py`)", ""]
failures = 0


def check(title: str, got, expected):
    global failures
    ok = sp.simplify(got - expected) == 0
    failures += 0 if ok else 1
    lines.append(f"- {'PASS' if ok else 'FAIL'} **{title}**: `{sp.sstr(sp.simplify(got))}` "
                 f"{'==' if ok else '!='} `{sp.sstr(expected)}`")


def spot(title: str, expr, values: dict, expected: float, rel=1e-6):
    global failures
    got = float(expr.subs(values).evalf())
    ok = abs(got - expected) <= rel * abs(expected)
    failures += 0 if ok else 1
    lines.append(f"- {'PASS' if ok else 'FAIL'} spot {title}: {got:.7g} vs hand {expected:.7g}")


# --- definitions --------------------------------------------------------------------
ode = sp.Eq(lam.diff(t), (1 - lam) / t_r - alpha * gd * lam)
eta_of_lam = eta_inf * (1 + beta * lam)
lines += ["## Definitions", "",
          f"- kinetics: `{sp.sstr(ode)}`",
          f"- viscosity: `eta = {sp.sstr(eta_of_lam)}`",
          "- source constants (blood_rheology.py): k_build = 1/t_r, k_break = alpha, "
          "gamma_c = k_build/k_break = 1/(alpha t_r), eta_0 = eta_inf (1 + beta)", "",
          "## Results", ""]

# 1. steady state from dlam/dt = 0
lam_s = sp.symbols("lambda_s", positive=True)
ss = sp.solve(sp.Eq(0, (1 - lam_s) / t_r - alpha * gd * lam_s), lam_s)
assert len(ss) == 1
lam_ss = ss[0]
check("steady state lam_ss = 1/(1 + alpha t_r gd)", lam_ss, 1 / (1 + alpha * t_r * gd))
# the product is the only combination present: substituting (alpha, t_r) -> (c alpha, t_r/c)
c = sp.symbols("c", positive=True)
check("lam_ss invariant under alpha -> c alpha, t_r -> t_r/c (only the product enters)",
      lam_ss.subs({alpha: c * alpha, t_r: t_r / c}, simultaneous=True), lam_ss)

# 2. steady viscosity is Cross with m = 1
eta_ss = eta_of_lam.subs(lam, lam_ss)
eta_0, lam_c = sp.symbols("eta_0 lambda_c", positive=True)
cross_m1 = eta_inf + (eta_0 - eta_inf) / (1 + lam_c * gd)
check("steady eta is Cross(m = 1) with eta_0 = eta_inf (1 + beta), lam_c = alpha t_r",
      eta_ss, cross_m1.subs({eta_0: eta_inf * (1 + beta), lam_c: alpha * t_r}))
check("eta_ss at gd -> 0 is eta_inf (1 + beta)", sp.limit(eta_ss, gd, 0), eta_inf * (1 + beta))
check("eta_ss at gd -> oo is eta_inf", sp.limit(eta_ss, gd, sp.oo), eta_inf)
check("eta_ss at alpha t_r gd = 1 is the plateau mean",
      eta_ss.subs(gd, 1 / (alpha * t_r)), eta_inf * (1 + beta / 2))

# 3. step response at constant rate
sol = sp.dsolve(ode, lam, ics={lam.subs(t, 0): lam0})
tau = 1 / (1 / t_r + alpha * gd)
expected = lam_ss + (lam0 - lam_ss) * sp.exp(-t / tau)
check("step response lam(t) = lam_ss + (lam0 - lam_ss) exp(-t/tau), 1/tau = 1/t_r + alpha gd",
      sol.rhs, expected)
check("tau at gd = 0 is t_r (rebuild time is the rest relaxation time)", tau.subs(gd, 0), t_r)

# 4. numeric spots, computed by hand
# source constants: eta_inf = 3.5e-3, eta_0 = 0.2 -> beta = 0.2/3.5e-3 - 1 = 57.142857 - 1
spot("beta from the source constants", eta_0 / eta_inf - 1, {eta_0: 0.2, eta_inf: 3.5e-3},
     56.142857142857)
# gamma_c = 5 1/s -> alpha t_r = 0.2 s; at gd = 5, lam_ss = 1/(1 + 1) = 0.5, eta = eta_inf(1 + 28.0714) = 0.10175
# NB the source is not self-consistent here: its steady curve uses GAMMA_C = 5 while its
# loop uses k_build = 1, k_break = 0.05, i.e. gamma_c = 20. My first spot check used the
# loop's constants against the steady curve's gamma_c and failed at 0.1607 vs 0.10175,
# which is how the inconsistency was found. The steady constants are used below.
spot("eta_ss at gd = gamma_c = 5 with the source's steady constants (alpha t_r = 0.2)", eta_ss,
     {eta_inf: 3.5e-3, beta: 56.142857142857, alpha: 0.2, t_r: 1.0, gd: 5.0}, 0.10175)
# step from lam0 = 1 at gd = 20, alpha = 0.05, t_r = 1: 1/tau = 1 + 1 = 2, lam_ss = 0.5,
# lam(0.5) = 0.5 + 0.5 exp(-1) = 0.5 + 0.18393972 = 0.68393972
spot("lam(t = 0.5) after a step to gd = 20 from lam0 = 1", sol.rhs,
     {alpha: 0.05, t_r: 1.0, gd: 20.0, lam0: 1.0, t: 0.5}, 0.68393972058572)

# 5. what a step transient adds once the steady curve has fixed a = alpha t_r
a_prod = sp.symbols("a", positive=True)
tau_of_a = t_r / (1 + a_prod * gd)          # tau with alpha = a/t_r substituted
check("with a = alpha t_r fixed, tau = t_r/(1 + a gd), i.e. t_r = tau (1 + a gd)",
      tau.subs(alpha, a_prod / t_r), tau_of_a)
tau_sym = sp.symbols("tau", positive=True)
frac = 1 - sp.exp(-t / tau_sym)              # fraction of the step completed at time t
t95 = sp.solve(sp.Eq(frac, sp.Rational(19, 20)), t)
assert len(t95) == 1
check("95 % of the step is complete at t = tau ln 20", t95[0], tau_sym * sp.log(20))
gd0, gd1 = sp.symbols("gammadot_0 gammadot_1", positive=True)
sigma_step = gd1 * eta_of_lam.subs(lam, expected.subs({gd: gd1, lam0: lam_ss.subs(gd, gd0)}))
# hand: a = 0.2 s, gd1 = 1 -> lam_ss = 1/1.2 = 0.83333333; gd0 = 300 -> lam0 = 1/61 = 0.016393443;
# tau = 2 s -> t_r = 2 (1 + 0.2) = 2.4 s, alpha = 0.2/2.4 = 0.083333333;
# lam(3) = 0.83333333 + (0.016393443 - 0.83333333) e^-1.5 = 0.83333333 - 0.81693989 x 0.22313016
#        = 0.83333333 - 0.18228393 = 0.65104940; sigma = 1 x 3e-3 x (1 + 10 x 0.65104940) = 0.022531482 Pa
spot("stress 3 s after a 300 -> 1 step, a = 0.2 s, t_r = 2.4 s, eta_inf = 3 mPa s, beta = 10",
     sigma_step, {alpha: 0.2 / 2.4, t_r: 2.4, gd0: 300.0, gd1: 1.0, eta_inf: 3e-3, beta: 10.0, t: 3.0},
     0.022531482)
spot("95 % time for tau = 2 s", tau_sym * sp.log(20), {tau_sym: 2.0}, 5.9914645)

lines += ["", f"**{failures} failure(s).**"]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print("\n".join(lines))
sys.exit(1 if failures else 0)
