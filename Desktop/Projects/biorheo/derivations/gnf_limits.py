"""SymPy derivation of every limiting case listed in ``biorheo.constitutive.gnf``.

Writes ``gnf_limits.md`` beside itself and exits non-zero if any limit fails. The
numeric spot checks evaluate the *SymPy* expressions, not the package, so they are an
anchor independent of the code under test; ``tests/test_gnf.py`` then checks the code
against the same closed forms.

Run:  python derivations/gnf_limits.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import sympy as sp

gd, tau_y, k, n, eta_0, eta_inf, lam, a, m, eta_c, mm, eps, eta_max = sp.symbols(
    "gammadot tau_y k n eta_0 eta_inf lambda a m eta_c m_p epsilon eta_max", positive=True)

OUT = Path(__file__).with_name("gnf_limits.md")
lines: list[str] = ["# GNF limiting cases (SymPy, generated by `gnf_limits.py`)", ""]
failures = 0


def check(title: str, expr, expected, subs=None, at=None):
    """Assert ``expr == expected`` symbolically (after ``subs``) or as a limit ``at``."""
    global failures
    e = expr.subs(subs) if subs else expr
    if at is not None:
        var, point = at
        got = sp.limit(e, var, point)
    else:
        got = sp.simplify(e)
    ok = (got == expected) if expected in (sp.oo, -sp.oo) else sp.simplify(got - expected) == 0
    failures += 0 if ok else 1
    lines.append(f"- {'PASS' if ok else 'FAIL'} **{title}**: `{sp.sstr(got)}` "
                 f"{'==' if ok else '!='} `{sp.sstr(expected)}`")
    return ok


def spot(title: str, expr, values: dict, expected: float, rel=1e-6):
    """Numeric evaluation of the SymPy expression at a hand-computed point."""
    global failures
    got = float(expr.subs(values).evalf())
    ok = abs(got - expected) <= rel * abs(expected)
    failures += 0 if ok else 1
    lines.append(f"- {'PASS' if ok else 'FAIL'} spot {title}: {got:.7g} vs hand {expected:.7g}")


# --- definitions (rate space) --------------------------------------------------------
PL = k * gd ** (n - 1)
HB = tau_y / gd + k * gd ** (n - 1)
CASSON = (sp.sqrt(tau_y / gd) + sp.sqrt(eta_c)) ** 2
CY = eta_inf + (eta_0 - eta_inf) * (1 + (lam * gd) ** a) ** ((n - 1) / a)
CROSS = eta_inf + (eta_0 - eta_inf) / (1 + (lam * gd) ** m)

lines += ["## Definitions", "",
          f"- power law: `eta = {sp.sstr(PL)}`",
          f"- Herschel-Bulkley: `eta = {sp.sstr(HB)}`, i.e. `sigma = tau_y + k gd^n`",
          f"- Casson: `eta = {sp.sstr(CASSON)}`, i.e. `sqrt(sigma) = sqrt(tau_y) + sqrt(eta_c gd)`",
          f"- Carreau-Yasuda: `eta = {sp.sstr(CY)}`",
          f"- Cross: `eta = {sp.sstr(CROSS)}`", "", "## Limits", ""]

# --- Herschel-Bulkley ------------------------------------------------------------------
check("HB, tau_y = 0 is the power law", HB, PL, subs={tau_y: 0})
check("HB, n = 1 is Bingham", HB, tau_y / gd + k, subs={n: 1})
check("HB stress at gd -> 0 is tau_y (n = 1/2 representative)", (HB * gd).subs(n, sp.Rational(1, 2)),
      tau_y, at=(gd, 0))
check("HB eta at gd -> 0 diverges (n = 1/2)", HB.subs(n, sp.Rational(1, 2)), sp.oo, at=(gd, 0))
check("HB stress/(k gd^n) at gd -> oo is 1 (n = 1/2)",
      (HB * gd / (k * gd ** n)).subs(n, sp.Rational(1, 2)), 1, at=(gd, sp.oo))
spot("HB at gd = 10 (Carbopol ETD2020 fit)", HB,
     {gd: 10, tau_y: 23.756, k: 8.903, n: 0.4526}, 4.9002, rel=2e-4)

# --- power law -------------------------------------------------------------------------
check("PL, n = 1 is Newtonian", PL, k, subs={n: 1})
spot("PL at gd = 4, k = 2, n = 1/2", PL, {gd: 4, k: 2, n: sp.Rational(1, 2)}, 1.0)

# --- Casson ----------------------------------------------------------------------------
check("Casson, tau_y = 0 is Newtonian", CASSON, eta_c, subs={tau_y: 0})
check("Casson expands as eta_c + 2 sqrt(tau_y eta_c/gd) + tau_y/gd", sp.expand(CASSON),
      eta_c + 2 * sp.sqrt(tau_y * eta_c / gd) + tau_y / gd)
check("Casson at gd -> oo is eta_c", CASSON, eta_c, at=(gd, sp.oo))
check("Casson stress at gd -> 0 is tau_y", CASSON * gd, tau_y, at=(gd, 0))
spot("Casson at gd = 100, tau_y = 4, eta_c = 0.01", CASSON, {gd: 100, tau_y: 4, eta_c: sp.Rational(1, 100)}, 0.09)

# --- Carreau-Yasuda --------------------------------------------------------------------
CY_ = CY.subs({a: 2, n: sp.Rational(2, 5)})  # representative exponents; sp.limit needs numbers
check("CY at gd -> 0 is eta_0 (a = 2, n = 2/5)", CY_, eta_0, at=(gd, 0))
check("CY at gd -> oo is eta_inf (a = 2, n = 2/5)", CY_, eta_inf, at=(gd, sp.oo))
check("CY, n = 1 is flat eta_0", CY, eta_0, subs={n: 1})
check("CY/(eta_0 lam^(n-1) gd^(n-1)) at gd -> oo is 1 when eta_inf = 0 (a = 2, n = 2/5)",
      (CY_ / (eta_0 * lam ** sp.Rational(-3, 5) * gd ** sp.Rational(-3, 5))).subs(eta_inf, 0), 1,
      at=(gd, sp.oo))
spot("CY at gd = sqrt(3), eta_0 = 1, eta_inf = 0, lam = 1, a = 2, n = 1/2", CY,
     {gd: sp.sqrt(3), eta_0: 1, eta_inf: 0, lam: 1, a: 2, n: sp.Rational(1, 2)}, 1 / 2 ** 0.5)

# --- Cross -----------------------------------------------------------------------------
CR_ = CROSS.subs(m, sp.Rational(7, 10))
check("Cross at gd -> 0 is eta_0 (m = 7/10)", CR_, eta_0, at=(gd, 0))
check("Cross at gd -> oo is eta_inf (m = 7/10)", CR_, eta_inf, at=(gd, sp.oo))
check("Cross at lam gd = 1 is the midpoint", CROSS, eta_inf + (eta_0 - eta_inf) / 2, subs={gd: 1 / lam})
check("Cross/(eta_0 lam^-m gd^-m) at gd -> oo is 1 when eta_inf = 0 (m = 7/10)",
      (CR_ / (eta_0 * (lam * gd) ** sp.Rational(-7, 10))).subs(eta_inf, 0), 1, at=(gd, sp.oo))
spot("Cross at gd = 9, eta_0 = 1, eta_inf = 0.1, lam = 1, m = 1", CROSS,
     {gd: 9, eta_0: 1, eta_inf: sp.Rational(1, 10), lam: 1, m: 1}, 0.19)

# --- regularisations (Bingham) ---------------------------------------------------------
lines += ["", "## Regularisations (yield term replacing tau_y/gd)", ""]
PAP = tau_y * (1 - sp.exp(-mm * gd)) / gd
BE = tau_y / sp.sqrt(gd ** 2 + eps ** 2)
check("Papanastasiou at gd -> 0 is tau_y m", PAP, tau_y * mm, at=(gd, 0))
check("Papanastasiou at gd -> oo recovers tau_y/gd (ratio -> 1)", PAP / (tau_y / gd), 1, at=(gd, sp.oo))
check("Bercovier-Engelman at gd = 0 is tau_y/eps", BE, tau_y / eps, subs={gd: 0})
check("Bercovier-Engelman at gd -> oo recovers tau_y/gd (ratio -> 1)", BE / (tau_y / gd), 1, at=(gd, sp.oo))
# bi-viscosity crossing for Bingham: eta_max gd_c = tau_y + k gd_c
gd_c = sp.solve(sp.Eq(eta_max * gd, tau_y + k * gd), gd)[0]
check("bi-viscosity crossing for Bingham, gd_c = tau_y/(eta_max - k)", gd_c, tau_y / (eta_max - k))
check("... and there eta_exact = eta_max, so clamp and bi-viscosity coincide",
      (tau_y / gd + k).subs(gd, gd_c), eta_max)
spot("Papanastasiou Bingham error at gd = 1, m = 1: -e^-1/2", (PAP + k - (tau_y / gd + k)) / (tau_y / gd + k),
     {gd: 1, tau_y: 1, k: 1, mm: 1}, -0.1839397)
# induced error closed form for Bingham + Papanastasiou: -tau_y e^{-m gd}/(tau_y + k gd)
err = sp.simplify((PAP + k - (tau_y / gd + k)) / (tau_y / gd + k))
check("Papanastasiou Bingham induced error is -tau_y e^(-m gd)/(tau_y + k gd)", err,
      -tau_y * sp.exp(-mm * gd) / (tau_y + k * gd))

lines += ["", f"**{failures} failure(s).**", ""]
OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print("\n".join(lines))
sys.exit(1 if failures else 0)
