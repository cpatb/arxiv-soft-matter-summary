"""Why the OpenFOAM plane-Couette anchor can impose its comparison shear rate.

`scripts/openfoam_couette_anchor.py` compares OpenFOAM's viscosity against
`record.eta_at(U0/H)`. That is only legitimate if the shear rate in the converged
solution is exactly `U0/H`, everywhere, for a non-Newtonian fluid too. This file derives
that and states the condition it needs.

Setting: incompressible, steady, fully developed 1-D flow `u = (u(y), 0, 0)` between
plates at `y = 0` (u = 0) and `y = H` (u = U0), no imposed pressure gradient along x
(periodic in x). The x-momentum equation reduces to

    d/dy [ tau(gd(y)) ] = 0,    gd = du/dy,

so `tau` is the SAME constant `tau_c` in every cell. The shear rate then solves
`tau(gd) = tau_c` pointwise.

THE CONDITION IS MONOTONICITY OF THE STRESS `tau(gd) = eta(gd) * gd`, NOT OF `eta(gd)`.
Every generalised Newtonian fluid biorheo ships is shear-THINNING, so `eta` is
decreasing while `tau` increases; requiring monotone `eta` would be both wrong and
unsatisfied. If `tau` is strictly increasing on `gd > 0` then `tau(gd) = tau_c` has a
unique root, `gd(y)` is the same constant everywhere, and integrating with the two
boundary conditions gives `gd = U0/H` exactly and `u` linear. A `tau` that is
non-monotone admits several roots at one `tau_c` and hence genuinely non-uniform
(shear-banded) solutions; the anchor's A1 gate is what would catch that case, and this
script checks the monotonicity for the exact laws the anchor exports, INCLUDING the
viscosity clamp OpenFOAM applies (`eta -> min(eta, eta_max)`), which the naive argument
ignores.

Checked here:
  1. `d(tau)/d(gd) > 0` symbolically for Herschel-Bulkley (0 < n <= 1) and for Casson.
  2. The clamped laws `tau = min(eta(gd), eta_max) * gd` are continuous and strictly
     increasing across the clamp crossover, so the clamp does not create a second root.
  3. `gd = U0/H` follows from a constant `gd` and the two wall conditions.
  4. Numeric spot checks at the actual Carbopol and blood parameters, at three rates
     each, that `tau` is increasing and that the root of `tau(gd) = tau(gd*)` is unique
     over the record's whole envelope (a bisection on a bracket, not an identity).

Run:  python derivations/couette_uniform_shear.py       (exits non-zero on any failure)
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import sympy as sp

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from biorheo.registry.loader import load_all  # noqa: E402

gd, y, H, U0, tau_y, k, n, eta_c, eta_max, C = sp.symbols(
    "gammadot y H U_0 tau_y k n eta_c eta_max C", positive=True)

OUT = Path(__file__).with_name("couette_uniform_shear.md")
lines: list[str] = ["# Uniform shear in plane Couette for a GNF "
                    "(SymPy, generated by `couette_uniform_shear.py`)", ""]
failures = 0


def check(title: str, ok: bool, detail: str = "") -> None:
    global failures
    failures += 0 if ok else 1
    lines.append(f"- {'PASS' if ok else 'FAIL'} **{title}**{': ' + detail if detail else ''}")


# --------------------------------------------------------------- 1. tau is increasing

lines += ["## 1. The stress is strictly increasing in the shear rate", "",
          "The condition the uniqueness argument needs is on `tau`, not on `eta`. Both "
          "laws below are shear-thinning (`eta` DECREASING), so a condition on `eta` "
          "would fail while the correct one holds.", ""]

tau_hb = tau_y + k * gd ** n                      # Herschel-Bulkley
eta_hb = tau_hb / gd
d_tau_hb = sp.simplify(sp.diff(tau_hb, gd))       # k n gd^(n-1) > 0 for every n > 0
check("HB d(tau)/d(gd) > 0", sp.simplify(d_tau_hb) == sp.simplify(k * n * gd ** (n - 1)),
      f"`{sp.sstr(d_tau_hb)}`, positive for k, n, gd > 0")
d_eta_hb = sp.simplify(sp.diff(eta_hb, gd).subs({n: sp.Rational(1, 2)}))
check("HB eta is DECREASING at n = 1/2 (so a condition on eta would be the wrong one)",
      sp.simplify(d_eta_hb.subs({tau_y: 1, k: 1, gd: 1})) < 0, f"`{sp.sstr(d_eta_hb)}`")

# Casson: sqrt(tau) = sqrt(tau_y) + sqrt(eta_c gd)  ->  tau = (sqrt(tau_y/gd)+sqrt(eta_c))^2 * gd
tau_ca = (sp.sqrt(tau_y) + sp.sqrt(eta_c * gd)) ** 2
eta_ca = sp.simplify(tau_ca / gd)
check("Casson eta matches the module's form (sqrt(tau_y/gd) + sqrt(eta_c))^2",
      sp.simplify(eta_ca - (sp.sqrt(tau_y / gd) + sp.sqrt(eta_c)) ** 2) == 0)
d_tau_ca = sp.simplify(sp.diff(tau_ca, gd))
check("Casson d(tau)/d(gd) > 0", bool(sp.simplify(d_tau_ca > 0).subs(
    {tau_y: 1, eta_c: 1, gd: 1})), f"`{sp.sstr(d_tau_ca)}` = eta_c + sqrt(tau_y eta_c/gd)")

# ------------------------------------------------------- 2. the clamp keeps it monotone

lines += ["", "## 2. OpenFOAM's viscosity clamp does not create a second root", "",
          "OpenFOAM evaluates `nu = min(nu0, model)`, i.e. `eta = min(eta_max, eta(gd))`. "
          "Because both families are shear-thinning, `eta(gd) > eta_max` exactly below "
          "some crossover `gd_x`, so the clamped stress is `eta_max * gd` for "
          "`gd < gd_x` and `tau(gd)` above it. The first branch is linear with positive "
          "slope, the second is increasing by part 1, and the two agree at `gd_x` by "
          "construction -- so the clamped stress is continuous and strictly increasing, "
          "and the root is still unique. What the clamp DOES change is the answer: below "
          "`gd_x` the exported law is not the record. That is why the anchor sets "
          "`eta_max` ten times above the top of the envelope and `export_report` reports "
          "`cap_binds`.", ""]

gd_x = sp.symbols("gammadot_x", positive=True)
clamped_lo = eta_max * gd
check("clamped branches agree at the crossover (HB)",
      sp.simplify((clamped_lo - tau_hb).subs(eta_max, (tau_hb / gd).subs(gd, gd_x))
                  .subs(gd, gd_x)) == 0)
check("the low branch has positive slope", sp.diff(clamped_lo, gd) == eta_max)

# ------------------------------------------------- 3. constant gd + the wall conditions

lines += ["", "## 3. A constant shear rate plus the two wall conditions gives U0/H", ""]
c = sp.symbols("c")
u = sp.integrate(c, (y, 0, y))                      # u(0) = 0 built in
sol = sp.solve(sp.Eq(u.subs(y, H), U0), c)[0]
check("gd = U0/H", sp.simplify(sol - U0 / H) == 0, f"`u(y) = {sp.sstr(sol * y)}`")
lines += ["", "So the anchor's comparison rate is IMPOSED by the boundary conditions and "
              "the domain height, with no constitutive parameter in it. A1 (the measured "
              "uniformity of `du/dy` across the gap) is the check that the solver found "
              "this branch and not another.", ""]

# --------------------------------------------------------------- 4. numeric spot checks

lines += ["## 4. Numeric spot checks at the shipped record parameters", "",
          "Not an identity: `tau` is evaluated on a dense grid over each record's own "
          "envelope and checked for strict increase, and the root of "
          "`tau(gd) = tau(gd_mid)` is bracketed by bisection to confirm it is unique.",
          "", "| record | model | envelope (1/s) | tau increasing | unique root | "
          "root vs gd_mid |", "|---|---|---|---|---|---|"]

for rid in ("carbopol_etd2020_0p1wt_30uL", "blood_horner2020_donor_A"):
    rec = load_all()[rid]
    lo, hi = rec.envelope.gammadot_min, rec.envelope.gammadot_max
    g = np.geomspace(lo, hi, 4000)
    tau = rec.eta_at(g) * g
    inc = bool(np.all(np.diff(tau) > 0))
    gmid = float(np.sqrt(lo * hi))
    target = float(rec.eta_at(np.array([gmid]))[0] * gmid)
    crossings = int(np.sum(np.diff(np.sign(tau - target)) != 0))
    # bisect the single crossing and check it returns gmid
    i = int(np.argmin(np.abs(tau - target)))
    a, b = g[max(i - 1, 0)], g[min(i + 1, len(g) - 1)]
    for _ in range(200):
        m = 0.5 * (a + b)
        if float(rec.eta_at(np.array([m]))[0] * m) < target:
            a = m
        else:
            b = m
    root = 0.5 * (a + b)
    rel = abs(root - gmid) / gmid
    ok = inc and crossings == 1 and rel < 1e-12
    failures += 0 if ok else 1
    lines.append(f"| {rid} | {rec.model.name} | {lo:g} to {hi:g} | "
                 f"{'yes' if inc else 'NO'} | {crossings} crossing(s) | "
                 f"rel {rel:.2e} |")

lines += ["", f"**{failures} failure(s).**", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
raise SystemExit(1 if failures else 0)
