"""Write the 15 Carbopol ETD2020 registry records from the fit table in ``carbopol/``.

One source of truth: ``Desktop/Projects/carbopol/hb_fits_etd2020.csv``, produced by
``carbopol/fit_hb.py`` from the deposited flow curves (DOI 10.25835/hjn2qcvy). This
script re-emits it as one YAML record per condition and nothing else; edit the CSV (or
the fit) upstream, never the YAML. Re-running must be byte-identical.

The envelope is each curve's own measured rate range read from the deposited csv
(about 1e-3 to 200 1/s); temperature and geometry come from the dataset description in
``carbopol/CARBOPOL_RHEOLOGY_LITERATURE.md``: 20 C, smooth 50 mm parallel plates, 0.5 mm
gap. Smooth plates leave slip uncontrolled, so each
``tau_y`` is a lower bound; the record says so in ``notes``.

Run:  python scripts/records_from_carbopol.py
"""

from __future__ import annotations

import csv
import re
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
CSV = HERE.parents[1] / "carbopol" / "hb_fits_etd2020.csv"
OUT = HERE.parent / "src" / "biorheo" / "registry" / "records"

DATA = HERE.parents[1] / "carbopol" / "data" / "etd2020_biermann2024"
TEMPERATURE_C = 20.0
GEOMETRY = "smooth 50 mm parallel plates, 0.5 mm gap, stress-controlled sweep"

TEMPLATE = """\
# generated by scripts/records_from_carbopol.py from carbopol/hb_fits_etd2020.csv; do not edit
id: {id}
fluid: Carbopol ETD2020 {wt} wt%, {tea} uL triethanolamine per 100 g, in water
model: herschel_bulkley
parameters:
  tau_y: {{value: {tau_y}, unit: Pa}}
  k: {{value: {k}, unit: Pa*s**{n}}}
  n: {{value: {n}, unit: dimensionless}}
envelope:
  gammadot_min: {{value: {gmin:.6g}, unit: 1/s}}
  gammadot_max: {{value: {gmax:.6g}, unit: 1/s}}
  temperature_C: {temp:g}
  geometry: {geometry}
sources:
  - {{doi: 10.25835/hjn2qcvy, role: dataset}}
  - {{doi: 10.3390/ma18133164, role: paper}}
licence:
  name: CC BY-NC-SA 4.0
  commercial_use: false
notes: >-
  Herschel-Bulkley fit (tau = tau_y + k gd^n) to the replicate mean of 3 stress
  sweeps, 54 points, curve_fit with sigma = tau (relative weighting) and tau_y bounded
  to [0, 1.5 tau_min]; R2 = {r2}. The rate is recovered as tau/eta at every point
  because the deposited rate column is rounded to two decimals. Smooth plates: slip is
  uncontrolled, so tau_y is a lower bound. Licence is non-commercial; this record is
  for validation and demonstration only.
extra:
  carbomer_wt_pct: {wt}
  tea_uL_per_100g: {tea}
  fit_R2: {r2}
  fit_script: carbopol/fit_hb.py
"""


def rate_range(wt: str, tea: str) -> tuple[float, float]:
    """Measured rate range of one condition, recovered as tau/eta exactly as
    ``fit_hb.load`` does (the deposited rate column is rounded to two decimals)."""
    import io
    path = DATA / f"ETD2020-{int(float(wt) * 10):02d}wt-{tea}ul.csv"
    raw = io.open(path, encoding="latin-1").read().splitlines()
    rows = [r.split(";") for r in raw[2:] if r.strip()]
    num = lambda c: float(c.replace(",", ".")) if c.strip() else float("nan")
    a = np.array([[num(c) for c in r] for r in rows])
    gd = np.nanmean(a[:, [2, 4, 6]] / (a[:, [3, 5, 7]] * 1e-3), axis=1)
    gd = gd[np.isfinite(gd) & (gd > 0)]
    assert gd.size == 54, (path, gd.size)
    return float(gd.min()), float(gd.max())


def main() -> None:
    rows = list(csv.DictReader(CSV.open(encoding="utf-8")))
    assert len(rows) == 15, len(rows)
    OUT.mkdir(exist_ok=True)
    for r in rows:
        m = re.fullmatch(r"([\d.]+) wt%, (\d+) uL TEA", r["condition"])
        assert m, r["condition"]
        wt, tea = m.group(1), m.group(2)
        rec_id = f"carbopol_etd2020_{wt.replace('.', 'p')}wt_{tea}uL"
        gmin, gmax = rate_range(wt, tea)
        text = TEMPLATE.format(
            id=rec_id, wt=wt, tea=tea, tau_y=r["tau_y_Pa"], k=r["K_Pa_sn"], n=r["n"],
            r2=r["R2"], gmin=gmin, gmax=gmax, temp=TEMPERATURE_C, geometry=GEOMETRY,
        )
        (OUT / f"{rec_id}.yaml").write_text(text, encoding="utf-8", newline="\n")
        print("wrote", rec_id)


if __name__ == "__main__":
    main()
