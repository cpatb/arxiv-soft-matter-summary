"""Write registry records per human donor from the Horner 2020 steady-shear data, with
their identifiability sidecars, and the model-comparison table that says what those 20
curves actually determine.

Three families are written per donor: ``casson`` (the one the source study publishes),
and ``cross`` and ``carreau_yasuda`` (the two that fit the same curves 5x better). The
Casson ids are UNSUFFIXED -- ``blood_horner2020_donor_A`` -- and the other two carry a
``_cross`` / ``_carreau_yasuda`` suffix. That asymmetry is ugly and deliberate: the
unsuffixed ids are pinned by tests, by the injectability case study and by the OpenFOAM
anchor, and renaming them to gain symmetry would have been a rename with no result
attached. Added 2026-09-06 for NEXT_STEPS item 6 (the L3 bridge for the families that
have no yield stress), which needs a record of each new family to export; all 20 donors
are written rather than one, because the export's refusal-on-verdict is only a
measurement over the whole set.

One source of truth: ``data/horner2020/steady_shear_human.csv`` (16 rates x 20 donors,
stress in Pa at 37 C) and ``physiology_and_casson_farrington2023.csv`` (the authors'
Casson values, hematocrit, fibrinogen, sex); provenance and hashes in
``data/horner2020/SOURCE.md``. Re-running is byte-identical apart from the sidecar's
``written_on`` date.

Three things happen, each a check:

1. The authors' Casson table is REPRODUCED before anything is built on it: an unweighted
   least-squares line through (sqrt(gd), sqrt(tau)) over all 16 points returns their
   (tau_y, eta_c) to 1e-8 (``MAX_REPRO_DEV``); the script stops if it does not.
2. Each donor is fitted with ``biorheo.identify`` (log-viscosity residuals, profiled at
   95 %). The record carries THAT fit, because the sidecar must describe the record's
   own numbers; the authors' values and the objective difference go in ``extra``. The
   difference (tau_y 0.4-71 % lower here, median 33 %) is a statement about the Casson
   form, which both fits misfit systematically: the log-residuals ordered by rate form
   3 runs on 18 of 20 donors (z = -3.1; the minimum possible at n = 16 is -3.62 for
   2 runs), and the sidecar's ``residual_structure`` says so. The same test on the
   AUTHORS' OWN sqrt-space residuals flags 18 of 20, so the misfit is not an artefact
   of the log-eta objective. Cross and Carreau-Yasuda misfit 5x less, at the price of
   lam and a being degenerate or bounded on about a third of donors.
3. Cross and Carreau-Yasuda are fitted to the same curves and their rmse and verdicts
   tabulated beside Casson's in ``data/horner2020/model_comparison.md``: which model
   the data determines is the finding, not the Casson numbers.

Run:  python scripts/records_from_horner.py
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import numpy as np

from biorheo.constitutive import get_model
from biorheo.identify.fit import RUNS_Z
from biorheo.identify import fit_rate_curve, runs_test, write_identifiability
from biorheo.registry import load_record

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "data" / "horner2020"
OUT = HERE.parent / "src" / "biorheo" / "registry" / "records"
TEMPERATURE_C = 37.0
GEOMETRY = "ARES-G2 double-wall concentric cylinder, EDTA-anticoagulated whole blood, rate sweep"
DOI_PAPER = "10.1007/s00397-023-01402-2"
MAX_REPRO_DEV = 1e-6   # relative; the authors' table reproduces to 1.2e-8
OUTLIERS = {"F", "N", "K"}  # DonorOutliers.xlsx, the paper's own list; carried, not applied
CASSON = get_model("casson")
COMPARE = ("casson", "herschel_bulkley", "cross", "carreau_yasuda")

TEMPLATE = """\
# generated by scripts/records_from_horner.py from data/horner2020/*.csv; do not edit
id: {id}
fluid: human whole blood, donor {donor} (Horner 2020), hematocrit {hct:g} %, fibrinogen {fib:g} mg/dL
model: casson
parameters:
  tau_y: {{value: {tau_y:.6g}, unit: Pa}}
  eta_c: {{value: {eta_c:.6g}, unit: Pa*s}}
envelope:
  gammadot_min: {{value: {gmin:.6g}, unit: 1/s}}
  gammadot_max: {{value: {gmax:.6g}, unit: 1/s}}
  temperature_C: {temp:g}
  geometry: {geometry}
sources:
  - {{doi: {doi}, role: paper}}
licence:
  name: not stated (author-posted workbook; Horner 2020 dissertation citation requested)
  commercial_use: false
notes: >-
  Casson fit (eta = (sqrt(tau_y/gd) + sqrt(eta_c))^2) by biorheo.identify to the 16-point
  steady-shear curve, log-viscosity residuals. The authors' own Casson values for this
  donor (extra.authors_casson_*) come from an unweighted line through
  (sqrt(gd), sqrt(tau)), reproduced here to {repro_dev:.1e}; the two objectives differ by
  {dtau:+.0%} in tau_y and {deta:+.0%} in eta_c because Casson misfits the curve
  systematically (see the sidecar's residual_structure). Not a licensed dataset: for
  validation and demonstration only.
extra:
  donor: {donor}
  sex: {sex}
  hematocrit_pct: {hct:g}
  fibrinogen_mg_per_dL: {fib:g}
  paper_outlier_flag: {outlier}
  authors_casson_tau_y_Pa: {a_tau:.6g}
  authors_casson_eta_c_Pa_s: {a_eta:.6g}
  authors_casson_objective: unweighted least squares in (sqrt(gd), sqrt(tau)), all 16 points
  authors_casson_reproduced_to: {repro_dev:.1e}
  dataset_file: steady_shear_human.csv
  dataset_md5: 0d53329ee629efa583655f26f88b89a1
"""


# The two families added 2026-09-06 for the L3 non-yield bridge. Casson keeps its own
# template because its notes carry the authors'-objective comparison, which these do not
# have: the source study publishes no Cross or Carreau-Yasuda table, so there is nothing
# to reproduce and the record's numbers are biorheo's fit and only that.
EXTRA_FAMILIES = ("cross", "carreau_yasuda")

TEMPLATE_FIT_ONLY = """\
# generated by scripts/records_from_horner.py from data/horner2020/*.csv; do not edit
id: {id}
fluid: human whole blood, donor {donor} (Horner 2020), hematocrit {hct:g} %, fibrinogen {fib:g} mg/dL
model: {model}
parameters:
{param_block}\
envelope:
  gammadot_min: {{value: {gmin:.6g}, unit: 1/s}}
  gammadot_max: {{value: {gmax:.6g}, unit: 1/s}}
  temperature_C: {temp:g}
  geometry: {geometry}
sources:
  - {{doi: {doi}, role: paper}}
licence:
  name: not stated (author-posted workbook; Horner 2020 dissertation citation requested)
  commercial_use: false
notes: >-
  {model} fit ({form}) by biorheo.identify to the 16-point steady-shear curve,
  log-viscosity residuals. Objective: unweighted least squares on log(eta), the same one
  used for this donor's Casson record {casson_id}. The source study publishes no {model}
  table, so unlike the Casson record there is nothing here to reproduce and these numbers
  are biorheo's fit alone. This family fits the curve rmse {rmse:.3f} against Casson's
  {rmse_casson:.3f}, at the price of the verdicts in the sidecar. Not a licensed dataset:
  for validation and demonstration only.
extra:
  donor: {donor}
  sex: {sex}
  hematocrit_pct: {hct:g}
  fibrinogen_mg_per_dL: {fib:g}
  paper_outlier_flag: {outlier}
  casson_record_same_curve: {casson_id}
  rmse_log_this_model: {rmse:.6g}
  rmse_log_casson: {rmse_casson:.6g}
  dataset_file: steady_shear_human.csv
  dataset_md5: 0d53329ee629efa583655f26f88b89a1
"""


def _param_block(model, values) -> str:
    """The `parameters:` body, one `name: {value, unit}` line per parameter, units taken
    from the model's own `units` dict so a record can never disagree with the model."""
    return "".join(f"  {n}: {{value: {v:.6g}, unit: {model.units[n]}}}\n"
                   for n, v in zip(model.param_names, values))


def load() -> tuple[np.ndarray, dict[str, np.ndarray], dict[str, dict]]:
    with open(DATA / "steady_shear_human.csv", newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    head, body = rows[0], np.array(rows[1:], dtype=float)
    gd = body[:, 0]
    stress = {h.replace("stress_Pa_", ""): body[:, i] for i, h in enumerate(head) if i > 0}
    phys = {}
    with open(DATA / "physiology_and_casson_farrington2023.csv", newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            phys[r["donor"]] = r
    print(f"steady shear: {gd.size} rates in [{gd.min():g}, {gd.max():g}] 1/s, {len(stress)} donors; "
          f"physiology rows: {len(phys)}")
    assert set(stress) == set(phys), (set(stress) ^ set(phys))
    return gd, stress, phys


def authors_casson(gd: np.ndarray, tau: np.ndarray) -> tuple[float, float, float]:
    """The authors' objective, back-solved 2026-09-05: unweighted line in sqrt space.
    Also returns the runs-test z of THEIR fit's log-eta residuals ordered by rate, the
    anchor that the misfit is not a property of biorheo's objective."""
    slope, intercept = np.polyfit(np.sqrt(gd), np.sqrt(tau), 1)
    tau_fit = (intercept + slope * np.sqrt(gd)) ** 2
    z_authors = runs_test(np.log(tau) - np.log(tau_fit)).z
    return float(intercept ** 2), float(slope ** 2), float(z_authors)


def main() -> None:
    gd, stress, phys = load()
    OUT.mkdir(parents=True, exist_ok=True)
    table = ["# Which model do 20 human blood flow curves determine?", "",
             "Generated by `scripts/records_from_horner.py`; every number reproduces by running "
             "it. 16 rates in [0.1, 700] 1/s per donor, 37 C. `rmse` is the root-mean-square "
             "log-viscosity residual (a relative error); `runs z` is the Wald-Wolfowitz score of "
             "the residual signs ordered by rate (below -2: systematic misfit); verdicts are "
             "the 95 % profile-likelihood closure per parameter (m = measurable, b = bounded "
             "one side, d = degenerate with a partner, n = not identifiable).", "",
             "| donor | Hct % | " + " | ".join(f"{m} rmse / runs z / verdicts" for m in COMPARE) + " |",
             "|---|---|" + "---|" * len(COMPARE)]
    worst_repro = 0.0
    n_authors_structured = 0
    n_runs_hist: dict[int, int] = {}
    summary = {m: {"rmse": [], "structured": 0, "verdicts": {}} for m in COMPARE}
    for donor in sorted(stress):
        tau = stress[donor]
        eta = tau / gd
        p = phys[donor]
        a_tau, a_eta, z_authors = authors_casson(gd, tau)
        n_authors_structured += z_authors < RUNS_Z
        dev = max(abs(a_tau / (float(p["casson_tau_y_mPa"]) * 1e-3) - 1.0),
                  abs(a_eta / (float(p["casson_eta_mPa_s"]) * 1e-3) - 1.0))
        worst_repro = max(worst_repro, dev)
        if dev > MAX_REPRO_DEV:
            sys.exit(f"donor {donor}: authors' Casson values NOT reproduced (dev {dev:.2e}); "
                     f"the objective is not the one recorded, stop")
        fits = {}
        for m in COMPARE:
            fits[m] = fit_rate_curve(get_model(m), gd, eta, temperature_C=TEMPERATURE_C, geometry=GEOMETRY)
        ident = fits["casson"]
        tau_y, eta_c = ident.values
        nr = ident.residual_structure.n_runs
        n_runs_hist[nr] = n_runs_hist.get(nr, 0) + 1
        rec_id = f"blood_horner2020_donor_{donor}"
        text = TEMPLATE.format(
            id=rec_id, donor=donor, hct=float(p["hematocrit_pct"]), fib=float(p["fibrinogen_mg_per_dL"]),
            sex=p["sex"], tau_y=tau_y, eta_c=eta_c, gmin=gd.min(), gmax=gd.max(), temp=TEMPERATURE_C,
            geometry=GEOMETRY, doi=DOI_PAPER, repro_dev=dev, dtau=tau_y / a_tau - 1.0,
            deta=eta_c / a_eta - 1.0, outlier=str(donor in OUTLIERS).lower(), a_tau=a_tau, a_eta=a_eta)
        path = OUT / f"{rec_id}.yaml"
        path.write_text(text, encoding="utf-8", newline="\n")
        rec = load_record(path, allow_network=False)
        write_identifiability(rec, ident, data_note="Horner 2020 steady shear, human donor "
                              f"{donor}, 16 points; see data/horner2020/SOURCE.md")
        for fam in EXTRA_FAMILIES:
            f = fits[fam]
            fid = f"{rec_id}_{fam}"
            ftext = TEMPLATE_FIT_ONLY.format(
                id=fid, donor=donor, hct=float(p["hematocrit_pct"]),
                fib=float(p["fibrinogen_mg_per_dL"]), sex=p["sex"], model=fam,
                param_block=_param_block(f.model, f.values), gmin=gd.min(), gmax=gd.max(),
                temp=TEMPERATURE_C, geometry=GEOMETRY, doi=DOI_PAPER,
                form=f.model.notes.split(";")[0], casson_id=rec_id,
                rmse=f.fit.rmse_log, rmse_casson=ident.fit.rmse_log,
                outlier=str(donor in OUTLIERS).lower())
            fpath = OUT / f"{fid}.yaml"
            fpath.write_text(ftext, encoding="utf-8", newline="\n")
            write_identifiability(load_record(fpath, allow_network=False), f,
                                  data_note="Horner 2020 steady shear, human donor "
                                  f"{donor}, 16 points; see data/horner2020/SOURCE.md")
        cells = []
        for m in COMPARE:
            f = fits[m]
            rs = f.residual_structure
            v = "".join(f.params[n].verdict[0] for n in f.model.param_names)
            cells.append(f"{f.fit.rmse_log:.3f} / {rs.z:+.1f} / {v}")
            summary[m]["rmse"].append(f.fit.rmse_log)
            summary[m]["structured"] += rs.structured
            for n in f.model.param_names:
                summary[m]["verdicts"].setdefault(n, {})
                summary[m]["verdicts"][n][f.params[n].verdict] = summary[m]["verdicts"][n].get(f.params[n].verdict, 0) + 1
        table.append(f"| {donor} | {float(p['hematocrit_pct']):g} | " + " | ".join(cells) + " |")
        print(f"{rec_id}: tau_y {tau_y * 1e3:.3f} mPa (authors {a_tau * 1e3:.3f}), eta_c {eta_c * 1e3:.3f} mPa s "
              f"(authors {a_eta * 1e3:.3f}); casson z {ident.residual_structure.z:+.2f} "
              f"({nr} runs), authors' own fit z {z_authors:+.2f}")
    table += ["", "## Summary over 20 donors", "",
              "| model | median rmse | max rmse | donors flagged structured | verdict counts |",
              "|---|---|---|---|---|"]
    for m in COMPARE:
        s = summary[m]
        vc = "; ".join(f"{n}: " + ", ".join(f"{k} {c}" for k, c in sorted(d.items())) for n, d in s["verdicts"].items())
        table.append(f"| {m} | {np.median(s['rmse']):.3f} | {max(s['rmse']):.3f} | {s['structured']}/20 | {vc} |")
    table += ["", f"Authors' Casson table reproduced to max relative deviation {worst_repro:.1e} "
              f"(objective: unweighted least squares in sqrt space, all 16 points).",
              "", "Casson runs on the log-eta fit, donors per run count: "
              + ", ".join(f"{k} runs: {v}" for k, v in sorted(n_runs_hist.items()))
              + f". The same runs test on the residuals of the AUTHORS' OWN sqrt-space fit flags "
              f"{n_authors_structured}/20 donors structured (z < {RUNS_Z}), so the misfit does not "
              f"depend on the objective. The minimum z possible at n = 16 is -3.62 (2 runs, 8/8 split).",
              "", "The rmse comparison is across parameter counts (2 for Casson, 4-5 for Cross and "
              "Carreau-Yasuda); the verdict column is the price paid: lam and a are degenerate or "
              "bounded on about a third of donors.", ""]
    (DATA / "model_comparison.md").write_text("\n".join(table) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(table[-len(COMPARE) - 4:]))


if __name__ == "__main__":
    main()
