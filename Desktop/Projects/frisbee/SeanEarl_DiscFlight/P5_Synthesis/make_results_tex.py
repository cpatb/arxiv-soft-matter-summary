"""
Emit `results_generated.tex`: every quantitative result in the manuscript, as
LaTeX macros and tables generated directly from the run artifacts.

The manuscript prose then refers to \\QbestHeading, \\QeastMean and so on rather
than to transcribed literals. This is deliberate: it makes it impossible for a
number in the paper to drift from the run that produced it, and it means the
whole results section regenerates if the pipeline is re-run.

Inputs
------
  ../P3_CFD/cfd_validation.json   validation verdicts (ABL, grid, convergence)
  ../P3_CFD/flow_fields.npz       sampled disc-altitude fields
  ../P4_Coupling/landing_stats.npz  Monte Carlo landing statistics
  Q.npz                           throwability metric
  hypothesis_check.json           hypothesis verdicts

Output
------
  results_generated.tex
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from conventions import (disc_altitude_index, horizontal_speed, pitch_mask,
                         u_ref_from_field)
from throwability import SPEED_FLOOR


_DIGIT_WORDS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three",
                "4": "Four", "5": "Five", "6": "Six", "7": "Seven",
                "8": "Eight", "9": "Nine"}


def digits_to_letters(v) -> str:
    """LaTeX control-word names may contain LETTERS ONLY.

    \\QmeanH90 does not define a macro called "QmeanH90" -- TeX reads the
    control word \\QmeanH and then the characters 9 and 0, so the macro is
    both undefined and silently prints stray digits. Heading numbers are
    therefore spelled out: 90 -> NineZero, 210 -> TwoOneZero.
    """
    return "".join(_DIGIT_WORDS.get(c, c) for c in str(v))


def macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def fmt(v, nd=2):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "n/a"
    return f"{v:.{nd}f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--Q", default="Q.npz")
    ap.add_argument("--fields", default="../P3_CFD/flow_fields.npz")
    ap.add_argument("--landings", default="../P4_Coupling/landing_stats.npz")
    ap.add_argument("--validation", default="../P3_CFD/cfd_validation.json")
    ap.add_argument("--hypotheses", default="hypothesis_check.json")
    ap.add_argument("--out", default="results_generated.tex")
    args = ap.parse_args()

    out = ["% GENERATED by P5_Synthesis/make_results_tex.py -- do not edit.\n",
           "% Every macro here is computed from a run artifact.\n\n"]

    Qd = np.load(args.Q, allow_pickle=False)
    L = np.load(args.landings, allow_pickle=False)
    F = np.load(args.fields, allow_pickle=False)
    Q = Qd["Q"]
    headings = [int(h) for h in Qd["headings"]]
    throws = [str(t) for t in L["throws"]]

    # ---------------- scope macros ---------------------------------------
    out.append(macro("Ndirections", len(headings)))
    out.append(macro("DirectionList",
                     ", ".join(f"${h}^\\circ$" for h in headings)))
    out.append(macro("NthrowsPerCell", int(L["n_throws"])))
    nlaunch = len(L["launch_x"]) * len(L["launch_y"])
    n_total = (nlaunch * len(headings) * len(throws) *
               len(L["bearings"]) * int(L["n_throws"]))
    out.append(macro("NlaunchPoints", nlaunch))
    out.append(macro("NbearingsList", len(L["bearings"])))
    out.append(macro("NtotalThrows", f"{n_total:,}".replace(",", "\\,")))
    out.append(macro("TargetRadius", fmt(float(L["target_radius_m"]), 0)))
    out.append(macro("TargetRange", fmt(float(L["target_range_m"]), 0)))

    # ---------------- per-heading Q --------------------------------------
    meanQ = {h: float(np.nanmean(Q[..., i])) for i, h in enumerate(headings)}
    maxQ = {h: float(np.nanmax(Q[..., i])) for i, h in enumerate(headings)}
    minQ = {h: float(np.nanmin(Q[..., i])) for i, h in enumerate(headings)}
    best = max(meanQ, key=meanQ.get)
    worst = min(meanQ, key=meanQ.get)
    out.append(macro("QbestHeading", best))
    out.append(macro("QworstHeading", worst))
    out.append(macro("QbestMean", fmt(meanQ[best], 4)))
    out.append(macro("QworstMean", fmt(meanQ[worst], 4)))
    ratio = meanQ[best] / meanQ[worst] if meanQ[worst] > 0 else float("inf")
    out.append(macro("QbestWorstRatio",
                     "$\\infty$" if not np.isfinite(ratio) else fmt(ratio, 1)))
    for h in headings:
        out.append(macro(f"QmeanH{digits_to_letters(h)}", fmt(meanQ[h], 4)))
        out.append(macro(f"QmaxH{digits_to_letters(h)}", fmt(maxQ[h], 4)))
        out.append(macro(f"QminH{digits_to_letters(h)}", fmt(minQ[h], 4)))

    # ---------------- disc-altitude wind ---------------------------------
    # Reference speed of the ABL inlet at 10 m; the sheltering fraction below
    # is quoted against it, so it must match the value used to drive the CFD.
    U_REF = u_ref_from_field(F, headings)
    zk, _z_off, _z_ok = disc_altitude_index(F["z"], 2.0)
    if not _z_ok:
        raise ValueError(f"nearest sampled altitude to 2 m is {float(F['z'][zk]):.2f} m")
    shelter_frac = []
    for h in headings:
        key = f"dir_{h:03d}__U"
        if key not in F.files:
            continue
        mag = horizontal_speed(F[key][:, :, zk, :])
        # restrict to the playing surface
        fx, fy = pitch_mask(F["x"], F["y"])
        sub = mag[np.ix_(fx, fy)]
        out.append(macro(f"UfieldMeanH{digits_to_letters(h)}", fmt(float(sub.mean()), 2)))
        out.append(macro(f"UfieldMinH{digits_to_letters(h)}", fmt(float(sub.min()), 2)))
        out.append(macro(f"UfieldMaxH{digits_to_letters(h)}", fmt(float(sub.max()), 2)))
        kk = F[f"dir_{h:03d}__k"][:, :, zk]
        ksub = kk[np.ix_(fx, fy)]
        I = np.sqrt(2 * np.maximum(ksub, 0) / 3) / np.maximum(sub, SPEED_FLOOR)
        out.append(macro(f"IfieldMeanH{digits_to_letters(h)}", fmt(float(I.mean()), 2)))
        shelter_frac.append(float(sub.mean()) / U_REF)
    out.append(macro("Uref", fmt(U_REF, 0)))
    if shelter_frac:
        # Sheltering expressed as a percentage of the 10 m reference, so the
        # manuscript never states the ratio in words that could drift away
        # from the numbers printed beside it.
        out.append(macro("UfieldFracMin", fmt(100 * min(shelter_frac), 0)))
        out.append(macro("UfieldFracMax", fmt(100 * max(shelter_frac), 0)))

    # ---------------- success rates by throw ------------------------------
    sr = L["success_rate"]
    for i, t in enumerate(throws):
        v = float(np.nanmean(sr[:, :, :, i, :]))
        out.append(macro("SR" + t.replace("_", ""), fmt(100 * v, 1)))
    for i, h in enumerate(headings):
        v = float(np.nanmean(sr[:, :, i, :, :]))
        out.append(macro(f"SRmeanH{digits_to_letters(h)}", fmt(100 * v, 1)))
    if "blocked_fraction" in L.files:
        out.append(macro("BlockedMean",
                         fmt(100 * float(np.nanmean(L["blocked_fraction"])), 1)))

    # The success factor that Q was ACTUALLY built from, and the all-throws
    # mean, kept as separate macros so the two can never be confused again.
    # tab:Qbyheading previously printed the all-throws mean beside a Q computed
    # from the hammer-excluded one: a reader multiplying the printed row got Q
    # wrong by a factor of ~1.5 and would reasonably conclude the pipeline was
    # broken.
    excluded = [str(t) for t in Qd["excluded_throws"]] \
        if "excluded_throws" in Qd.files else []
    kept_idx = [i for i, t in enumerate(throws) if t not in excluded]
    out.append(macro("SRexcluded",
                     fmt(100 * float(np.nanmean(Qd["success_rate"])), 1)))
    out.append(macro("SRallthrows",
                     fmt(100 * float(np.nanmean(sr)), 1)))
    out.append(macro("SRexcludedThrows",
                     ", ".join(t.replace("_", " ") for t in excluded)
                     or "none"))
    out.append(macro("SRkeptThrows",
                     ", ".join(throws[i].replace("_", " ") for i in kept_idx)))
    for i, h in enumerate(headings):
        v = float(np.nanmean(sr[:, :, i][..., kept_idx, :]))
        out.append(macro(f"SRkeptH{digits_to_letters(h)}", fmt(100 * v, 1)))

    # ---------------- validation verdicts --------------------------------
    if Path(args.validation).exists():
        V = json.loads(Path(args.validation).read_text())
        conv_verdicts: list[str] = []
        for r in V:
            t = r.get("test", "")
            if t == "abl_homogeneity":
                out.append(macro("ABLdrift",
                                 fmt(100 * r["worst_dU"], 1)))
                out.append(macro("ABLverdict", r["verdict"]))
            elif t == "grid_independence":
                out.append(macro("GridDiff", fmt(100 * r["worst_dU"], 1)))
                out.append(macro("GridDiffUref",
                                 fmt(100 * r.get("worst_dU_over_uref",
                                                 float("nan")), 1)))
                out.append(macro("GridVerdict", r["verdict"]))
            elif t == "convergence":
                nm = "Fine" if "coarse" not in r.get("case", "") else "Coarse"
                out.append(macro(f"Conv{nm}",
                                 fmt(100 * r["worst_pk_pk"], 1)))
                # WP4b item 10 [2026-09-03]: this branch emitted the two NUMBERS and no
                # verdict, while `abl_homogeneity` and `grid_independence` above both
                # emit one. So the only test in cfd_validation.json that records
                # "verdict": "FAIL" was also the only one with no macro to print it, and
                # the prose was left to characterise it in words. Emit it.
                out.append(macro(f"Conv{nm}Verdict", r["verdict"]))
                conv_verdicts.append(r["verdict"])
        # A single macro for the pair: FAIL if either mesh fails, so the paper cannot
        # quote a pass because one of the two happened to be quieter.
        if conv_verdicts:
            out.append(macro("ConvVerdict",
                             "FAIL" if "FAIL" in conv_verdicts else "PASS"))

    # ---------------- Q table ---------------------------------------------
    tbl = ["\n\\begin{table}[H]\n\\centering\\small\n",
           "\\begin{tabular}{lrrrrrr}\n\\toprule\n",
           "$\\theta_{\\text{wind}}$ & $\\bar Q$ & $Q_{\\min}$ & "
           "$Q_{\\max}$ & $\\overline{|U_{2\\text{m}}|}$ & "
           "$\\bar I_{2\\text{m}}$ & $\\bar S$ \\\\\n",
           " & & & & (m\\,s$^{-1}$) & & (\\%) \\\\\n\\midrule\n"]
    for i, h in enumerate(headings):
        key = f"dir_{h:03d}__U"
        um = "n/a"
        im = "n/a"
        if key in F.files:
            mag = horizontal_speed(F[key][:, :, zk, :])
            fx, fy = pitch_mask(F["x"], F["y"])
            sub = mag[np.ix_(fx, fy)]
            um = fmt(float(sub.mean()), 2)
            kk = F[f"dir_{h:03d}__k"][:, :, zk][np.ix_(fx, fy)]
            im = fmt(float((np.sqrt(2 * np.maximum(kk, 0) / 3) /
                            np.maximum(sub, SPEED_FLOOR)).mean()), 2)
        # The SAME success factor Q was built from -- read straight out of
        # Q.npz rather than recomputed here over a different set of throws.
        s = 100 * float(np.nanmean(Qd["success_rate"][..., i]))
        tbl.append(f"${h}^\\circ$ & {fmt(meanQ[h],4)} & {fmt(minQ[h],4)} & "
                   f"{fmt(maxQ[h],4)} & {um} & {im} & {fmt(s,1)} \\\\\n")
    tbl.append("\\bottomrule\n\\end{tabular}\n")
    excl_note = (
        f" $\\bar S$ is taken over the throw types that enter $Q$ "
        f"(\\SRkeptThrows); \\SRexcludedThrows{{}} "
        f"{'is' if len(excluded) == 1 else 'are'} excluded, because a fixed "
        f"\\TargetRange~m scoring target is unreachable for a throw of that "
        f"characteristic range, so its delivery rate measures the target "
        f"choice rather than the wind. Over all throw types $\\bar S$ would be "
        f"\\SRallthrows\\%, which does not multiply out to the $Q$ in "
        f"column~2."
    ) if excluded else ""
    tbl.append("\\caption{Throwability and its inputs, averaged over the "
               "playing surface, for each computed inflow direction. "
               "$\\bar S$ is the simulated delivery rate within "
               "\\TargetRadius~m of a \\TargetRange~m target." + excl_note +
               "}\n\\label{tab:Qbyheading}\n\\end{table}\n")
    out.append("\\newcommand{\\QbyHeadingTable}{%\n" + "".join(tbl) + "}\n")

    # ---------------- success-rate-by-throw table --------------------------
    t2 = ["\n\\begin{table}[H]\n\\centering\\small\n",
          "\\begin{tabular}{l" + "r" * len(headings) + "}\n\\toprule\n",
          "Throw & " + " & ".join(f"${h}^\\circ$" for h in headings) +
          " \\\\\n\\midrule\n"]
    pretty = {"right_backhand": "Backhand", "right_forehand": "Forehand",
              "hammer": "Hammer (exploratory)"}
    for i, t in enumerate(throws):
        row = [fmt(100 * float(np.nanmean(sr[:, :, j, i, :])), 1)
               for j in range(len(headings))]
        t2.append(f"{pretty.get(t, t)} & " + " & ".join(row) + " \\\\\n")
    t2.append("\\bottomrule\n\\end{tabular}\n")
    t2.append("\\caption{Simulated delivery rate (\\%) within "
              "\\TargetRadius~m of a \\TargetRange~m target, by throw type and "
              "inflow direction, averaged over launch positions and throw "
              "bearings.}\n\\label{tab:SRbythrow}\n\\end{table}\n")
    out.append("\\newcommand{\\SRbyThrowTable}{%\n" + "".join(t2) + "}\n")

    Path(args.out).write_text("".join(out))
    n_macros = sum(1 for line in out if line.startswith("\\newcommand"))
    print(f"wrote {args.out}: {n_macros} macros")
    print(f"  headings {headings}, best {best} (Qbar={meanQ[best]:.4f}), "
          f"worst {worst} (Qbar={meanQ[worst]:.4f})")


if __name__ == "__main__":
    main()
