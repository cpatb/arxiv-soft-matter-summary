"""
Generate LaTeX macros for the vertical-structure and release-height results.

Same contract as `make_results_tex.py`: every number the manuscript prints
about vertical structure is emitted here from the analysis JSON, so the prose
cannot drift away from the data. Digits are spelled out in macro names because
TeX control sequences may not contain digits.

Inputs
    ../P3_CFD/vertical_structure.json   from P3_CFD/vertical_structure.py
    ../P4_Coupling/height_sweep.json    from P4_Coupling/aggregate_height_sweep.py
                                        (optional; macros omitted if absent)
Output
    vertical_generated.tex
"""

from __future__ import annotations

import argparse
import json
import os

DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
          "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def digits_to_letters(s):
    return "".join(DIGITS.get(c, c) for c in str(s))


def macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def fmt(v, nd):
    return f"{float(v):.{nd}f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--vertical", default="../P3_CFD/vertical_structure.json")
    ap.add_argument("--height-sweep", default="../P4_Coupling/height_sweep.json")
    ap.add_argument("--out", default="vertical_generated.tex")
    args = ap.parse_args()

    V = json.load(open(args.vertical))
    out = ["% AUTO-GENERATED by P5_Synthesis/make_vertical_tex.py -- do not edit"]

    headings = sorted(int(k) for k in V if k.isdigit())
    out.append(macro("VertNdirections", len(headings)))

    # ---- per-heading disc-band quantities -------------------------------
    for h in headings:
        L = digits_to_letters(h)
        b = V[str(h)]["disc_band"]
        out.append(macro(f"VertSigmaBandH{L}", fmt(b["sigma"], 2)))
        out.append(macro(f"VertTIBandH{L}", fmt(b["TI"], 2)))
        out.append(macro(f"VertShearBandH{L}", fmt(b["dUdz"], 3)))
        out.append(macro(f"VertTLBandH{L}", fmt(b["T_L"], 1)))
        out.append(macro(f"VertLintBandH{L}", fmt(b["L_int"], 1)))
        # Dimensionless regime ratios: flight scales of a canonical 25 m throw.
        out.append(macro(f"VertTLratioH{L}", fmt(b["T_L"] / 2.5, 1)))
        out.append(macro(f"VertNeddyH{L}", fmt(25.0 / b["L_int"], 1)))

    def rng(vals, nd):
        lo, hi = min(vals), max(vals)
        return f"{fmt(lo, nd)}--{fmt(hi, nd)}"

    bands = [V[str(h)]["disc_band"] for h in headings]
    out.append(macro("VertTLrange", rng([b["T_L"] for b in bands], 1)))
    out.append(macro("VertLintRange", rng([b["L_int"] for b in bands], 1)))
    out.append(macro("VertTLratioRange",
                     rng([b["T_L"] / 2.5 for b in bands], 1)))
    out.append(macro("VertNeddyRange",
                     rng([25.0 / b["L_int"] for b in bands], 1)))
    out.append(macro("VertTIBandRange", rng([b["TI"] for b in bands], 2)))

    # ---- the no-buildings counterfactual --------------------------------
    if "counterfactual_2m" in V:
        cf = V["counterfactual_2m"]
        for h in headings:
            L = digits_to_letters(h)
            c = cf[str(h)]
            out.append(macro(f"VertUratioH{L}", fmt(c["U_ratio"], 2)))
            out.append(macro(f"VertSigRatioH{L}", fmt(c["sigma_ratio"], 2)))
            out.append(macro(f"VertTIpitchH{L}", fmt(c["TI_pitch"], 2)))
        any_h = str(headings[0])
        out.append(macro("VertTIcontrol", fmt(cf[any_h]["TI_empty"], 2)))
        out.append(macro("VertUratioRange",
                         rng([cf[str(h)]["U_ratio"] for h in headings], 2)))
        out.append(macro("VertSigRatioRange",
                         rng([cf[str(h)]["sigma_ratio"] for h in headings], 2)))
        out.append(macro("VertTIpitchRange",
                         rng([cf[str(h)]["TI_pitch"] for h in headings], 2)))

    # ---- how sigma_u grows with height ----------------------------------
    # Ratio of sigma_u at 6 m and at 10 m to its value at 2 m, per heading.
    for target, nm in ((6.0, "Six"), (10.0, "Ten"), (20.0, "Twenty")):
        vals = []
        for h in headings:
            z = V[str(h)]["z"]
            s = V[str(h)]["sigma"]
            i2 = min(range(len(z)), key=lambda i: abs(z[i] - 2.0))
            it = min(range(len(z)), key=lambda i: abs(z[i] - target))
            vals.append(s[it] / s[i2])
        out.append(macro(f"VertSigGrowth{nm}", rng(vals, 1)))

    # ---- release-height sweep (optional) --------------------------------
    if os.path.exists(args.height_sweep):
        H = json.load(open(args.height_sweep))
        rows = H["rows"]
        lo, hi = rows[0], rows[-1]
        out.append(macro("HeightZmin", fmt(lo["z"], 1)))
        out.append(macro("HeightZmax", fmt(hi["z"], 1)))
        out.append(macro("HeightExcessMin", fmt(lo["sigma_excess"], 2)))
        out.append(macro("HeightExcessMax", fmt(hi["sigma_excess"], 2)))
        out.append(macro("HeightExcessGrowth",
                         fmt(hi["sigma_excess"] /
                             max(lo["sigma_excess"], 1e-9), 1)))
        out.append(macro("HeightSigmaGustMin", fmt(lo["sigma_gust"], 2)))
        out.append(macro("HeightSigmaGustMax", fmt(hi["sigma_gust"], 2)))
        out.append(macro("HeightFracMin", f"{100*lo['excess_fraction']:.0f}"))
        out.append(macro("HeightFracMax", f"{100*hi['excess_fraction']:.0f}"))
        out.append(macro("HeightNlevels", len(rows)))
    else:
        print(f"note: {args.height_sweep} absent; height macros omitted")

    with open(args.out, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {args.out}: {len(out)-1} macros")


if __name__ == "__main__":
    main()
